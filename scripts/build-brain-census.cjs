// ---------------------------------------------------------------------------
// scanMethodologyCommands() - read every commands/*.md, extract the
// frontmatter block between the first two lines that are exactly three
// hyphens, and from files carrying "kind: methodology" extract the
// single-line inline frameworks: [...] array. commandCount is DERIVED from
// disk at run time (Part 11 ethos), never a frozen literal.
// ---------------------------------------------------------------------------
function scanMethodologyCommands() {
  let files = [];
  try {
    files = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    files = [];
  }

  const usageMap = new Map();
  let commandCount = 0;

  for (const file of files) {
    const abs = path.join(COMMANDS_DIR, file);
    let content;
    try {
      content = fs.readFileSync(abs, 'utf8');
    } catch (_e) {
      continue;
    }
    const lines = content.split('\n');
    let firstDash = -1;
    let secondDash = -1;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].trim() === '---') {
        if (firstDash === -1) {
          firstDash = i;
        } else {
          secondDash = i;
          break;
        }
      }
    }
    if (firstDash === -1 || secondDash === -1) continue;

    const fm = lines.slice(firstDash + 1, secondDash).join('\n');
    if (!/^kind:\s*methodology\s*$/m.test(fm)) continue;
    commandCount++;

    const m = fm.match(/^frameworks:\s*\[(.*)\]\s*$/m);
    if (!m) continue;
    const inner = m[1];
    const nameRe = /"([^"]*)"/g;
    let mm;
    while ((mm = nameRe.exec(inner)) !== null) {
      const name = mm[1];
      if (!name) continue;
      usageMap.set(name, (usageMap.get(name) || 0) + 1);
    }
  }

  const frameworks = Array.from(usageMap.entries())
    .map(([name, uses]) => ({ name, uses }))
    .sort((a, b) => (b.uses - a.uses) || a.name.localeCompare(b.name));

  return {
    commandCount,
    scannedAt: new Date().toISOString().slice(0, 10),
    frameworks,
  };
}

// ---------------------------------------------------------------------------
// brainCall(toolName, args, key) - direct fetch POST to BRAIN_URL/mcp, the
// exact wire shape lib/core/brain-client.cjs uses (headers, jsonrpc 2.0
// tools/call body, SSE "data: " line parse). Two deliberate differences from
// brain-client (research Pitfall 2): on a non-OK response, return
// { ok:false, httpStatus, bodyText } with the body read VERBATIM, never null;
// and no session cache. No initialize handshake is required up front (the
// transport is stateless at the HTTP level); if the server ever rejects with
// a session-required error, this mirrors _ensureSession's single initialize
// call once and retries.
// ---------------------------------------------------------------------------
function _looksSessionRequired(bodyText) {
  return typeof bodyText === 'string' && /session/i.test(bodyText) && /required|missing|invalid/i.test(bodyText);
}

async function _initializeOnce(key) {
  const res = await fetch(BRAIN_URL + '/mcp', {
    method: 'POST',
    signal: AbortSignal.timeout(BRAIN_REQUEST_TIMEOUT_MS),
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json, text/event-stream',
      Authorization: 'Bearer ' + key,
    },
    body: JSON.stringify({
      jsonrpc: '2.0',
      id: 1,
      method: 'initialize',
      params: {
        protocolVersion: '2024-11-05',
        capabilities: {},
        clientInfo: { name: 'mindrian-census', version: '1.0.0' },
      },
    }),
  });
  try {
    await res.text();
  } catch (_e) {
    /* drain best-effort */
  }
  return res.ok;
}

// Phase 259 (TRUST-02): classify a caught error into the D-05 failure-kind
// taxonomy at the site where the error object still exists. Measured live
// this session on Node v22.23.1: an AbortSignal.timeout abort yields
// e.name === 'TimeoutError' (e.code === 23, message "The operation was
// aborted due to timeout"); a connection failure yields a plain TypeError
// with message "fetch failed" and no distinguishing name. Once brainCall
// returns, both collapse into the same 'fetch failed: ...' bodyText prefix,
// so e.message alone cannot tell them apart downstream -- classify HERE.
function _classifyThrown(e) {
  return (e && e.name === 'TimeoutError') ? 'timeout' : 'hard_error';
}

async function brainCall(toolName, args, key) {
  const doCall = async () =>
    fetch(BRAIN_URL + '/mcp', {
      method: 'POST',
      signal: AbortSignal.timeout(BRAIN_REQUEST_TIMEOUT_MS),
      headers: {
        'Content-Type': 'application/json',
        Accept: 'application/json, text/event-stream',
        Authorization: 'Bearer ' + key,
      },
      body: JSON.stringify({
        jsonrpc: '2.0',
        id: 2,
        method: 'tools/call',
        params: { name: toolName, arguments: args },
      }),
    });

  let res;
  try {
    res = await doCall();
  } catch (e) {
    return { ok: false, httpStatus: 0, bodyText: 'fetch failed: ' + (e && e.message ? e.message : String(e)), errorKind: _classifyThrown(e) };
  }

  if (!res.ok) {
    let bodyText = '';
    try {
      bodyText = await res.text();
    } catch (_e) {
      bodyText = '';
    }
    if (_looksSessionRequired(bodyText)) {
      const initOk = await _initializeOnce(key).catch(() => false);
      if (initOk) {
        let retryRes;
        try {
          retryRes = await doCall();
        } catch (e) {
          return { ok: false, httpStatus: 0, bodyText: 'retry fetch failed: ' + (e && e.message ? e.message : String(e)), errorKind: _classifyThrown(e) };
        }
        if (!retryRes.ok) {
          let retryBody = '';
          try {
            retryBody = await retryRes.text();
          } catch (_e) {
            retryBody = '';
          }
          return { ok: false, httpStatus: retryRes.status, bodyText: retryBody, errorKind: 'hard_error' };
        }
        res = retryRes;
      } else {
        return { ok: false, httpStatus: res.status, bodyText, errorKind: 'hard_error' };
      }
    } else {
      return { ok: false, httpStatus: res.status, bodyText, errorKind: 'hard_error' };
    }
  }

  let text;
  try {
    text = await res.text();
  } catch (e) {
    return { ok: false, httpStatus: res.status, bodyText: 'body read failed: ' + (e && e.message ? e.message : String(e)), errorKind: 'malformed' };
  }
  const dataLine = text.split('\n').find((l) => l.startsWith('data: '));
  if (!dataLine) {
    return { ok: false, httpStatus: res.status, bodyText: 'no SSE data line in response: ' + text.slice(0, 500), errorKind: 'malformed' };
  }
  let parsed;
  try {
    parsed = JSON.parse(dataLine.slice(6));
  } catch (e) {
    return { ok: false, httpStatus: res.status, bodyText: 'unparsable SSE payload: ' + text.slice(0, 500), errorKind: 'malformed' };
  }
  if (parsed.error) {
    // OQ-3 (carried risk, A1): classified hard_error under D-05's "anything
    // that did not cleanly succeed VOIDs regardless of bucket" rule. Risk:
    // if orchestration_readiness ever errors on an unknown framework name
    // rather than returning a readiness object, every genuinely-absent
    // framework would VOID instead of MISS. Not discharged at research
    // time; discharged by the live floor-run checkpoint in Plan 259-04.
    return { ok: false, httpStatus: res.status, bodyText: JSON.stringify(parsed.error), errorKind: 'hard_error' };
  }
  if (parsed.result && Array.isArray(parsed.result.content)) {
    const textContent = parsed.result.content.find((c) => c && c.type === 'text');
    if (textContent) {
      try {
        return { ok: true, result: JSON.parse(textContent.text) };
      } catch (_e) {
        return { ok: true, result: { text: textContent.text } };
      }
    }
  }
  return { ok: true, result: parsed.result || null };
}

// ---------------------------------------------------------------------------
// computeGapTable(laneA) - frameworks with readiness 0-2 or absent, sorted by
// uses descending then name. This ordered list IS "top gaps by expected-use"
// and IS the Phase 249 enrichment queue seed.
// ---------------------------------------------------------------------------
function computeGapTable(laneA) {
  if (!laneA || !Array.isArray(laneA.frameworks)) return [];
  const gaps = [];
  for (const row of laneA.frameworks) {
    const readiness = row.readiness && row.readiness.ok ? row.readiness : null;
    const score =
      readiness && readiness.result && readiness.result.readiness && typeof readiness.result.readiness.readiness_score === 'number'
        ? readiness.result.readiness.readiness_score
        : null;
    const isGap = score === null || score <= 2;
    if (!isGap) continue;
    gaps.push({
      framework: row.name,
      uses: row.uses,
      readiness_score: score,
      status:
        readiness && readiness.result && readiness.result.readiness
          ? readiness.result.readiness.orchestration_status
          : null,
      reason:
        score === null
          ? 'readiness probe absent or failed - treated as a gap'
          : 'readiness ' + score + '/4',
    });
  }
  gaps.sort((a, b) => (b.uses - a.uses) || a.framework.localeCompare(b.framework));
  return gaps;
}

