// ---------------------------------------------------------------------------
const MD_RENDER_ONLY_EXCLUDED = Object.freeze({
  // 'commands/<name>.md': 'the documented reason this declaring command is exempt',
});

// ---------------------------------------------------------------------------
// stripFrontmatter(content) -- return the body text after the closing `---`,
// or the whole string when no frontmatter block is found.
// ---------------------------------------------------------------------------
function stripFrontmatter(content) {
  const m = /^---\r?\n[\s\S]*?\r?\n---/.exec(content);
  return m ? content.slice(m[0].length) : content;
}

// ---------------------------------------------------------------------------
// buildMdKeyspace(opts) -- Phase 209-03 (B3). The PARALLEL .md keyspace walk
// over commands/*.md (opts.rootDir defaults to REPO_ROOT, so a fixture dir can
// be walked without touching the live tree). For every hitl_shape-declaring
// command (excluding 'none'), returns { surface, declared_shape, wired },
// where wired = (body carries stampFiring.STAMP_MARKER OR mentions
// 'AskUserQuestion') AND (the allowed-tools grant predicate is satisfied -
// reused via stampFiring.grantTool: it returns the content UNCHANGED exactly
// when the grant is either absent-and-unrestricted or already present, and
// CHANGED only when a restrictive list is missing the grant, i.e. NOT wired).
// A command listed in MD_RENDER_ONLY_EXCLUDED with a non-empty reason is
// exempt from the wired half (mirrors the .cjs render-only-excluded model).
// Keep the .cjs walk and its entries byte-identical; this function is
// additive, never repurposing listCjsFiles.
// ---------------------------------------------------------------------------
function buildMdKeyspace(opts) {
  opts = opts || {};
  const rootDir = opts.rootDir || REPO_ROOT;
  const dir = path.join(rootDir, 'commands');

  let files = [];
  try {
    files = fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    files = [];
  }

  const entries = [];
  for (const f of files) {
    const abs = path.join(dir, f);
    let content;
    try {
      content = fs.readFileSync(abs, 'utf8');
    } catch (_e) {
      continue;
    }
    const shape = stampFiring.parseShape(content);
    if (!shape || shape === 'none') continue;

    const surface = 'commands/' + f;
    const body = stripFrontmatter(content);
    const bodyWired = body.indexOf(stampFiring.STAMP_MARKER) !== -1 || body.indexOf('AskUserQuestion') !== -1;
    const toolWired = stampFiring.grantTool(content) === content;
    const wired = bodyWired && toolWired;

    const entry = { surface, declared_shape: shape, wired };
    if (Object.prototype.hasOwnProperty.call(MD_RENDER_ONLY_EXCLUDED, surface)) {
      const reason = MD_RENDER_ONLY_EXCLUDED[surface];
      if (typeof reason === 'string' && reason.trim().length > 0) {
        entry.excluded = true;
        entry.reason = reason.trim();
      }
    }
    entries.push(entry);
  }

  return entries;
}

