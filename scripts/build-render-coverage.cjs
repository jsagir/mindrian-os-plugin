function buildSkillKeyspace(opts) {
  opts = opts || {};
  const rootDir = opts.rootDir || REPO_ROOT;
  const dir = path.join(rootDir, 'skills');

  let dirNames = [];
  try {
    dirNames = fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort();
  } catch (_e) {
    dirNames = [];
  }

  const entries = [];
  for (const d of dirNames) {
    const abs = path.join(dir, d, 'SKILL.md');
    let content;
    try {
      content = fs.readFileSync(abs, 'utf8');
    } catch (_e) {
      continue;
    }
    const shape = stampFiring.parseShape(content);
    if (!shape || shape === 'none') continue;

    const surface = 'skills/' + d + '/SKILL.md';
    const body = stripFrontmatter(content);
    const bodyWired = body.indexOf(stampFiring.STAMP_MARKER) !== -1 || body.indexOf('AskUserQuestion') !== -1;
    const toolWired = stampFiring.grantTool(content) === content;
    const wired = bodyWired && toolWired;

    const entry = { surface, declared_shape: shape, wired };
    if (Object.prototype.hasOwnProperty.call(SKILL_RENDER_ONLY_EXCLUDED, surface)) {
      const reason = SKILL_RENDER_ONLY_EXCLUDED[surface];
      if (typeof reason === 'string' && reason.trim().length > 0) {
        entry.excluded = true;
        entry.reason = reason.trim();
      }
    }
    entries.push(entry);
  }

  return entries;
}

// ---------------------------------------------------------------------------
// buildRegistry() -- assemble the derived registry. Walks the render entry points,
// classifies each, derives the dispatcher shape vocabulary (the structural anchor),
// and computes the render_counts block. Returns the registry object PLUS a
// non-serialized `_excludeErrors` field (callers strip it before writing and fail on
// it). Pure: zero Brain, zero network.
// ---------------------------------------------------------------------------
function buildRegistry() {
  let dispatcherSrc = '';
  try {
    dispatcherSrc = fs.readFileSync(path.join(REPO_ROOT, DISPATCHER_REL), 'utf8');
  } catch (_e) {
    dispatcherSrc = '';
  }
  const dispatch = parseDispatcherShapes(dispatcherSrc);

  const walked = walkRenderEntryPoints();
  const entries = [];
  const excludeErrors = [];
  let cardEmission = 0;
  let renderOnlyExcluded = 0;

  const dialShape = dispatch.subShapes.includes('F.7-dial') ? 'F.7-dial' : null;

  for (const rec of walked) {
    const cls = classifyRenderCoverage(rec);
    const entry = {
      entry: rec.entry,
      kind: rec.kind,
      render_coverage: cls.render_coverage,
    };
    // The renderDial entries carry the F.7-dial shape handle so a consumer (178-02)
    // and the build test can key on shape without re-parsing the dispatcher.
    if (rec.kind === 'renderDial' && dialShape) {
      entry.shape = dialShape;
    }
    if (cls.reason) entry.reason = cls.reason;
    if (cls.note) entry.note = cls.note;
    if (cls.error) excludeErrors.push(cls.error);

    if (cls.render_coverage === 'card-emission') cardEmission += 1;
    else renderOnlyExcluded += 1;

    entries.push(entry);
  }

  // Phase 209-03 (B3): the SECOND, ADDITIVE keyspace - commands/*.md with
  // hitl_shape frontmatter. Appended AFTER the .cjs entries so the .cjs
  // entries stay byte-identical in position and content (Test 6/T-209-14).
  const mdEntries = buildMdKeyspace();
  let mdWired = 0;
  let mdUnwired = 0;
  for (const e of mdEntries) {
    if (e.excluded || e.wired) mdWired += 1;
    else mdUnwired += 1;
    entries.push(e);
  }

  // The intern-w1-mode-gate-skip fix: the THIRD, ADDITIVE keyspace -
  // skills/*/SKILL.md with hitl_shape frontmatter. Appended AFTER the
  // commands/*.md entries so both prior keyspaces stay byte-identical in
  // position and content.
  const skillEntries = buildSkillKeyspace();
  let skillWired = 0;
  let skillUnwired = 0;
  for (const e of skillEntries) {
    if (e.excluded || e.wired) skillWired += 1;
    else skillUnwired += 1;
    entries.push(e);
  }

  return {
    generated_note: GENERATED_NOTE,
    dispatcher: {
      source: DISPATCHER_REL.split(path.sep).join('/'),
      f_subshapes: dispatch.subShapes,
      has_dial_branch: dispatch.hasDialBranch,
    },
    render_counts: {
      card_emission: cardEmission,
      render_only_excluded: renderOnlyExcluded,
      md_declared_wired: mdWired,
      md_declared_unwired: mdUnwired,
      skill_declared_wired: skillWired,
      skill_declared_unwired: skillUnwired,
    },
    entries,
    _excludeErrors: excludeErrors,
  };
}

// Serialize exactly the way the on-disk file is written so the --check byte-compare
// is deterministic. Strips the non-serialized `_excludeErrors`. Mirrors
// build-connector-registry.cjs serializeRegistry (JSON.stringify(...,2) + trailing
// newline). The entries are ALREADY sorted by the walk; the key order here is the
// stable serialization order.
function serializeRegistry(reg) {
  const clean = {
    generated_note: reg.generated_note,
    dispatcher: reg.dispatcher,
    render_counts: reg.render_counts,
    entries: reg.entries,
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// main()
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);
  const reg = buildRegistry();
  const errs = [];
  for (const e of reg._excludeErrors) errs.push(e);

  if (argv.includes('--check')) {
    const next = serializeRegistry(reg);
    const onDisk = fs.existsSync(REGISTRY_PATH) ? fs.readFileSync(REGISTRY_PATH, 'utf8') : '';
    if (onDisk !== next) {
      errs.push(
        'data/render-coverage-registry.json is STALE (a render entry point appeared in code ' +
          'but is absent from the registry, OR the registry drifted). ' +
          'Run: node scripts/build-render-coverage.cjs'
      );
    }
    if (errs.length) {
      console.error(errs.join('\n'));
      console.error('Recovery: regenerate the render registry: node scripts/build-render-coverage.cjs');
      process.exit(1);
    }
    console.log('render-coverage-registry: OK');
    return;
  }

  // Default: write the registry, refusing on any render-only-excluded-without-reason.
  if (errs.length) {
    console.error(errs.join('\n'));
    console.error('Recovery: add a reason to the RENDER_ONLY_EXCLUDED entry, then re-run: node scripts/build-render-coverage.cjs');
    process.exit(1);
  }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(REGISTRY_PATH, serializeRegistry(reg));
  console.log(
    'Wrote data/render-coverage-registry.json (' +
      reg.entries.length + ' entries: ' +
      reg.render_counts.card_emission + ' card-emission, ' +
      reg.render_counts.render_only_excluded + ' render-only-excluded, ' +
      reg.render_counts.md_declared_wired + ' md-declared-wired, ' +
      reg.render_counts.md_declared_unwired + ' md-declared-unwired, ' +
      reg.render_counts.skill_declared_wired + ' skill-declared-wired, ' +
      reg.render_counts.skill_declared_unwired + ' skill-declared-unwired)'
  );
}

