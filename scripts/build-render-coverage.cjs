// ---------------------------------------------------------------------------
// listSourceFiles(scopeDirAbs) -- recursively enumerate every .cjs file under a
// scope dir, EXCLUDING *.test.cjs, deterministically sorted. Mirrors the
// build-connector-registry.cjs listSourceFiles idiom (readdir + filter + sort +
// try/catch-yields-[] when the dir is absent), extended to recurse into
// subdirectories because the render entry points live at arbitrary depth (lib/agents,
// lib/core/breakthrough, lib/hmi, lib/render, lib/workflow, scripts).
// ---------------------------------------------------------------------------
function listCjsFiles(scopeDirAbs) {
  const out = [];
  let entries;
  try {
    entries = fs.readdirSync(scopeDirAbs, { withFileTypes: true });
  } catch (_e) {
    return out;
  }
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const e of entries) {
    const abs = path.join(scopeDirAbs, e.name);
    if (e.isDirectory()) {
      out.push(...listCjsFiles(abs));
    } else if (e.isFile() && e.name.endsWith('.cjs') && !e.name.endsWith('.test.cjs')) {
      out.push(abs);
    }
  }
  return out;
}

// ---------------------------------------------------------------------------
// parseDispatcherShapes(dispatcherSrc) -- the AST/grep walk over the dispatcher.
// Extracts the F_SUBSHAPES array (selector-dispatcher.cjs:341) and confirms the
// F.7-dial dispatch branch (:755) exists. Returns { subShapes: [...], hasDialBranch }.
// This is the structural proof that the render-shape vocabulary the registry records
// is the SAME vocabulary the dispatcher routes; a new F.* branch added to the
// dispatcher changes this parse and so changes the derived registry (R-3 floor).
// Pure string parse, zero I/O beyond the single read in the caller.
// ---------------------------------------------------------------------------
function parseDispatcherShapes(dispatcherSrc) {
  const subShapes = [];
  // F_SUBSHAPES = ['F.0', 'F.1', ..., 'F.7-dial'];
  const m = /F_SUBSHAPES\s*=\s*\[([^\]]*)\]/.exec(dispatcherSrc);
  if (m) {
    const inner = m[1];
    const re = /['"]([^'"]+)['"]/g;
    let mm;
    while ((mm = re.exec(inner)) !== null) {
      subShapes.push(mm[1]);
    }
  }
  // The F.7-dial branch: `requestedShape === 'F.7-dial'`.
  const hasDialBranch = /requestedShape\s*===\s*['"]F\.7-dial['"]/.test(dispatcherSrc);
  return { subShapes, hasDialBranch };
}

// The walk's OWN file. The registry generator is uniquely the file that MUST carry
// the literal `pickShape(` / `renderDial(` tokens (the call-site regexes + the prose
// that documents them); it is NOT a render entry point. A generator never enumerates
// itself -- exactly as build-connector-registry.cjs is absent from its own connector
// ledger. This self-reference exclusion is the ONLY entry-point exclusion; it is
// documented, not a hand-maintained allow/deny list, and a NEW real call site in any
// OTHER file is still caught by the walk (the R-3 exhaustiveness floor stays intact).
const SELF_BASENAME = 'build-render-coverage.cjs';

// hasCallSite(src, token) -- TRUE when `src` contains a real `<token>(` call site on
// a NON-COMMENT, NON-REGEX-LITERAL line. A line that is a `//` or `*` comment is
// ignored (so a doc-mention never mints a phantom entry), and the `\b` word boundary
// + a deny of an immediately-preceding `\` (the regex-literal `\bpickShape` form)
// keeps a pattern literal from counting. A real invocation -- `pickShape(`,
// `dispatcher.pickShape(`, `presenter.renderDial(` -- matches. This is what makes the
// FLOOR test (Task 2) valid: a synthesized NEW real call site trips the walk; a mere
// textual mention does not.
function hasCallSite(src, token) {
  const callRe = new RegExp('(^|[^\\\\A-Za-z0-9_.])' + token + '\\s*\\(');
  const dotCallRe = new RegExp('\\.' + token + '\\s*\\(');
  for (const rawLine of src.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line.startsWith('//') || line.startsWith('*') || line.startsWith('/*')) continue;
    // Strip a trailing line comment so an inline `// pickShape(` note never counts.
    const code = rawLine.replace(/\/\/.*$/, '');
    if (dotCallRe.test(code) || callRe.test(code)) return true;
  }
  return false;
}

// ---------------------------------------------------------------------------
// walkRenderEntryPoints() -- the EXHAUSTIVE render-entry-point walk (C-1, R-3).
// Greps every .cjs file under lib/ and scripts/ (excluding *.test.cjs AND the
// generator's own file) for a real `pickShape(` call site and a real `renderDial(`
// call site (hasCallSite ignores comment/regex-literal mentions). Each MATCHED file
// yields one entry-point record PER call-site KIND it contains (a file calling BOTH
// pickShape and renderDial -- e.g. scripts/intent-classifier.cjs -- yields TWO
// records, one per kind, because they are two distinct render entry points). Returns
// the records sorted deterministically by (entry, kind). Pure: reads source files
// only; ZERO Brain, ZERO network (Part 8).
// ---------------------------------------------------------------------------
function walkRenderEntryPoints() {
  const records = [];

  for (const scope of WALK_SCOPES) {
    const scopeAbs = path.join(REPO_ROOT, scope);
    for (const fileAbs of listCjsFiles(scopeAbs)) {
      if (path.basename(fileAbs) === SELF_BASENAME) continue;
      let src;
      try {
        src = fs.readFileSync(fileAbs, 'utf8');
      } catch (_e) {
        continue;
      }
      const rel = path.relative(REPO_ROOT, fileAbs).split(path.sep).join('/');
      if (hasCallSite(src, 'pickShape')) {
        records.push({ entry: rel, kind: 'pickShape' });
      }
      if (hasCallSite(src, 'renderDial')) {
        records.push({ entry: rel, kind: 'renderDial' });
      }
    }
  }

  records.sort((a, b) => {
    if (a.entry !== b.entry) return a.entry.localeCompare(b.entry);
    return a.kind.localeCompare(b.kind);
  });
  return records;
}

// ---------------------------------------------------------------------------
// classifyRenderCoverage(rec) -- the two-state disposition derivation per entry.
// Returns { render_coverage, reason?, note?, error? }.
//
//   render-only-excluded : the entry-point identity "<entry>|<kind>" is in the
//                          RENDER_ONLY_EXCLUDED table (a render call site that never
//                          reaches a Decision Gate); the table value IS the required
//                          reason. A table entry with a blank reason yields an
//                          `error` so the build fails closed (D-178-07 / T-172-06).
//   card-emission        : the entry routes through the SEED-020 card-emission door.
//                          For a pickShape call site that is pickShape's isFShape
//                          host-append (selector-dispatcher.cjs:931-933, which appends
//                          the AskUserQuestion marker to ANY F* shape, including the
//                          dispatcher self-call). For a renderDial call site it is the
//                          150.5 engine-arm thread (the dial output's
//                          askuserquestion_marker is concatenated into the turn block;
//                          the F.7-dial shape -- starting with 'F' -- is host-appended).
// ---------------------------------------------------------------------------
function classifyRenderCoverage(rec) {
  const id = rec.entry + '|' + rec.kind;
  if (Object.prototype.hasOwnProperty.call(RENDER_ONLY_EXCLUDED, id)) {
    const reason = RENDER_ONLY_EXCLUDED[id];
    const out = { render_coverage: 'render-only-excluded' };
    if (typeof reason === 'string' && reason.trim().length > 0) {
      out.reason = reason.trim();
    } else {
      out.error =
        'render entry ' + id +
        ' is render-only-excluded but carries no reason (D-178-07 / T-172-06: no surface excluded by accident)';
    }
    return out;
  }

  // card-emission. Record WHY it is covered (the door it routes through). The
  // F.7-dial / dial-selector entry is host-appended because the renderDialShape
  // return carries shape 'F.7-dial' which starts with 'F', so pickShape's isFShape
  // branch appends the marker -- the registry records the reason, it does not demand
  // an in-renderDialShape marker assignment.
  const out = { render_coverage: 'card-emission' };
  if (rec.kind === 'renderDial') {
    out.note =
      'host-appended: the dial render carries shape F.7-dial (starts with F), so pickShape isFShape appends the AskUserQuestion marker; the renderDial output is threaded into the turn block via the 150.5 engine-arm seam';
  } else if (rec.entry === DISPATCHER_REL.split(path.sep).join('/')) {
    out.note =
      'dispatcher self-call: pickShape is defined and invoked here; the isFShape host-append (selector-dispatcher.cjs appendAskUserQuestionTrailer) mints the marker on every successful Shape F.* return';
  } else {
    out.note =
      'routes through pickShape isFShape host-append (the SEED-020 single construction door): a Shape F.* return gets the AskUserQuestion marker appended by the dispatcher';
  }
  return out;
}

// ---------------------------------------------------------------------------
// The md-keyspace render-only-EXCLUDED table (mirrors RENDER_ONLY_EXCLUDED above,
// the declared-implies-rendered escape hatch one plane up - Phase 209-03 B3).
// EMPTY by design at ship (the B1 stamp wired every live declaring command);
// the escape hatch exists structurally for a future exempt surface. An entry
// here requires a non-empty reason or the build fails closed, exactly like
