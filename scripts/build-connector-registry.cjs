    const onDiskLedger = fs.existsSync(LEDGER_PATH) ? fs.readFileSync(LEDGER_PATH, 'utf8') : '';
    if (onDiskLedger !== nextLedger) {
      errs.push('data/connector-coverage-ledger.json is STALE. Run: node scripts/build-connector-registry.cjs');
    }

    // Phase 198-04 (SPEC-2, Task 1): data/mcp-tool-connectors.json STALE
    // byte-compare -- same discipline as the registry + ledger above.
    const nextMcp = serializeMcpToolRegistry(reg._mcpToolRegistry);
    const onDiskMcp = fs.existsSync(MCP_CONNECTORS_PATH) ? fs.readFileSync(MCP_CONNECTORS_PATH, 'utf8') : '';
    if (onDiskMcp !== nextMcp) {
      errs.push('data/mcp-tool-connectors.json is STALE. Run: node scripts/build-connector-registry.cjs');
    }

    // The four CONN-03 connector validations (frozen-6 reach, frozen-3 posture,
    // WFL-01 resolver-resolution framework, no (sensor,reach,sub_mode) tuple
    // collision). Any failure is a hard exit 1.
    for (const e of validateConnectors(reg)) errs.push(e);

    // The R9 gap HARD-FAIL (Canon Part 11 R2/R9 / INV-10 step 3; the
