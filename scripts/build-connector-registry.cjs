// ---------------------------------------------------------------------------
// coerce(v) -- the value coercions the flat parser already does (null, boolean,
// integer, JSON array, quote-strip). Shared by the flat top-level walk and the
// nested connector descent so the two stay byte-identical in behavior.
// ---------------------------------------------------------------------------
function coerce(v) {
  if (v === '') return [];
  if (v === 'null' || v === '~') return null;
  if (v === 'true' || v === 'false') return v === 'true';
  if (/^-?\d+$/.test(v)) return parseInt(v, 10);
  if (v.startsWith('[')) {
    try {
      return JSON.parse(v);
    } catch (_e) {
      // Not strict JSON (e.g. `[SENS-02, SENS-07]` with unquoted tokens, the
      // common shape for sensor_triggers). Split the inner CSV into a trimmed,
      // quote-stripped array. An empty `[]` yields [].
      const inner = v.replace(/^\[/, '').replace(/\]$/, '').trim();
      if (inner === '') return [];
      return inner
        .split(',')
        .map((s) => s.trim().replace(/^["']|["']$/g, ''))
        .filter((s) => s.length > 0);
    }
  }
  return v.replace(/^["']|["']$/g, '');
}

// ---------------------------------------------------------------------------
// parseConnectorFrontmatter(md) -- the nested-map parser. Mirrors the flat
// parseFrontmatter in build-command-registry.cjs (lines 100-137) AND extends it
// to DESCEND one indent level into the `connector:` nested map: when a
// top-level key is `connector` with an empty value, subsequent indented
// `  key: value` lines are accumulated into out.connector as an object, with
// the SAME value coercions (null, booleans, integers, JSON arrays, indented
// dash-lists, quote-stripping). This nested descent is the ONE genuine net-new
// parsing concern this phase introduces.
// ---------------------------------------------------------------------------
function parseConnectorFrontmatter(md) {
  if (typeof md !== 'string') return {};
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md);
  if (!m) return {};
  const out = {};
  let key = null; // current top-level dash-list key

  // Nested-descent state: when we are inside the `connector:` map, every
  // indented line is parsed into `connectorObj` until a non-indented line ends
  // the block.
  let inConnector = false;
  let connectorObj = null;
  let connectorKey = null; // current nested dash-list key

  for (const rawLine of m[1].split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    const indented = /^\s+\S/.test(line);

    // While inside the connector map, an indented line is a nested sub-key (or a
    // nested dash-list item). A non-indented, non-blank line ends the block.
    if (inConnector) {
      if (line.trim() === '' || indented) {
        if (line.trim() === '') continue;
        // Strip the comment-only lines (e.g. `  # MUST match ...`).
        const noComment = line.replace(/\s+#.*$/, '');
        const subKv = /^\s+([A-Za-z0-9_-]+):\s*(.*)$/.exec(noComment);
        if (subKv) {
          connectorKey = subKv[1];
          const sv = subKv[2].trim();
          connectorObj[connectorKey] = coerce(sv);
          continue;
        }
        const subDash = /^\s+-\s+(.*)$/.exec(noComment);
        if (subDash && connectorKey) {
          if (!Array.isArray(connectorObj[connectorKey])) connectorObj[connectorKey] = [];
          connectorObj[connectorKey].push(subDash[1].replace(/^["']|["']$/g, ''));
          continue;
        }
        // An indented line that is neither (blank-after-trim handled above) is
        // ignored.
        continue;
      }
      // A non-indented line -> the connector block is done.
      inConnector = false;
      out.connector = connectorObj;
      connectorObj = null;
      connectorKey = null;
      // fall through to parse this line as a normal top-level line
    }

    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (kv) {
      key = kv[1];
      const v = kv[2].trim();
      if (key === 'connector' && v === '') {
        // Enter the nested descent. connectorObj accumulates the sub-keys.
        inConnector = true;
        connectorObj = {};
        connectorKey = null;
        continue;
      }
      out[key] = coerce(v);
    } else if (key && /^\s*-\s+/.test(line)) {
      if (!Array.isArray(out[key])) out[key] = [];
      out[key].push(line.replace(/^\s*-\s+/, '').replace(/^["']|["']$/g, ''));
    }
    // Any other line (blank, comment `# ...`) is ignored.
  }

  // EOF inside the connector block -> flush it.
  if (inConnector && connectorObj) out.connector = connectorObj;

  return out;
}

// ---------------------------------------------------------------------------
// Load the committed framework-name allowlist (the FEEDS_INTO-linked Brain
// slice UNION curated_extras). Mirrors build-command-registry.cjs verbatim --
// the connector generator REUSES the shipped data/framework-names.json; it adds
// NO new Brain query.
// ---------------------------------------------------------------------------
function loadFrameworkNames() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const names = Array.isArray(raw && raw.framework_names) ? raw.framework_names : [];
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return new Set([...names, ...extras]);
  } catch (_e) {
    return new Set();
  }
}

function loadCuratedExtras() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return extras.slice();
  } catch (_e) {
    return [];
  }
}

// ---------------------------------------------------------------------------
// Source-file discovery: walk commands/*.md AND skills/*/SKILL.md AND
// agents/*.md, deterministically sorted (commands, then skills, then agents),
// so the registry is byte-stable across machines. Returns [{ kind, file, base }]
// where the kind drives the surface id in buildRegistry(). The agents leg
// byte-mirrors the commands leg (the same readdirSync + .md filter + sort +
// try/catch-yields-[] when the dir is absent); an agent .md is parsed by the
// SAME parseConnectorFrontmatter and obeys the SAME one-connector-per-file
// contract, exactly like a command.
// ---------------------------------------------------------------------------
function listSourceFiles() {
  const out = [];

  let cmdFiles = [];
  try {
    cmdFiles = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    cmdFiles = [];
  }
  for (const f of cmdFiles) {
    out.push({ kind: 'command', file: path.join(COMMANDS_DIR, f), base: f.replace(/\.md$/, '') });
  }

  let skillDirs = [];
  try {
    skillDirs = fs
      .readdirSync(SKILLS_DIR, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();
  } catch (_e) {
    skillDirs = [];
  }
  for (const d of skillDirs) {
    const skillFile = path.join(SKILLS_DIR, d, 'SKILL.md');
    if (fs.existsSync(skillFile)) {
      out.push({ kind: 'skill', file: skillFile, base: d });
    }
  }

  let agentFiles = [];
  try {
    agentFiles = fs.readdirSync(AGENTS_DIR).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    agentFiles = [];
  }
  for (const f of agentFiles) {
    out.push({ kind: 'agent', file: path.join(AGENTS_DIR, f), base: f.replace(/\.md$/, '') });
  }

  return out;
}

// ---------------------------------------------------------------------------
// listMcpToolConnectorDescriptors() -- Phase 198-04 (SPEC-2, Task 1) MCP-tool
// discovery. Walks lib/mcp/tools/*.cjs (sorted, deterministic) PLUS the two
// named non-tools/ exporters (tool-router.cjs's MCP_TOOL_CONNECTORS,
// contract-version.cjs's connectors), requires each, and collects every raw
// descriptor from its exported array. Returns the RAW descriptors (each
// module's own {tool, surface, connector, hitl_shape, hitl_why, ...} shape) --
// normalizeMcpToolEntry() below maps them into the registry entry shape. A
// module that fails to load or export nothing is silently skipped (Wave-safe,
// mirrors listSourceFiles()'s try/catch-yields-[] discipline). Zero Brain/
// network calls -- pure filesystem + require.
// ---------------------------------------------------------------------------
function listMcpToolConnectorDescriptors() {
  const out = [];

  const namedModules = [
    { file: MCP_TOOL_ROUTER_PATH, exportKey: 'MCP_TOOL_CONNECTORS' },
    { file: MCP_CONTRACT_VERSION_PATH, exportKey: 'connectors' },
  ];
  for (const nm of namedModules) {
    if (!fs.existsSync(nm.file)) continue;
    let mod;
    try {
      mod = require(nm.file);
    } catch (_e) {
      continue;
    }
    const arr = mod && Array.isArray(mod[nm.exportKey]) ? mod[nm.exportKey] : [];
    for (const c of arr) out.push(c);
  }

  let toolFiles = [];
  try {
    toolFiles = fs.readdirSync(MCP_TOOLS_DIR).filter((f) => f.endsWith('.cjs')).sort();
  } catch (_e) {
    toolFiles = [];
  }
  for (const f of toolFiles) {
    let mod;
    try {
      mod = require(path.join(MCP_TOOLS_DIR, f));
    } catch (_e) {
      continue;
    }
    const arr = mod && Array.isArray(mod.connectors) ? mod.connectors : [];
    for (const c of arr) out.push(c);
  }

  return out;
}

// ---------------------------------------------------------------------------
// listMcpToolClaimedSources() -- Phase 235-02 (CIRS-02). The CENSUS half of the
// MCP-tool blind-spot fix. listMcpToolConnectorDescriptors() above answers "what
