// The four governed surface CLASSES (Canon Part 11 R1 four-class amendment,
// navigator-LOCKED 2026-06-23; externally grounded in the ArbiterOS
// governance-ISA paradigm, research/172-GOVERNOR-RESEARCH.md). Every governed
// surface carries EXACTLY ONE class. The four classes are the invocation
// governance ISA; the gate is class-aware. A fifth label, `utility-excluded`,
// is NOT one of the four governance classes -- it is the class slot for an
// EXCLUDED utility surface (the first-class conformant terminal state, R1), kept
// distinct so an excluded utility is never mis-counted as a governed class.
// This MINTS no new edge/node/reach and opens no Brain wire -- it NAMES existing
// surface types. The wired/excluded/gap COUNTS are UNCHANGED by the class field.
//   mechanical   -- a non-framework command/operation (plumbing that triggers a
//                   reach but is not itself a pws methodology).
//   framework    -- a pws methodology (declares frameworks: or a resolvable
//                   connector.framework).
//   intelligence -- an engine/sensor/analysis surface (rs-* / find-* / score-* /
//                   whitespace / diagnostics / radar / the intelligence
//                   orchestrator / analysis agents).
//   pipeline     -- a chain/workflow surface (act / discover / ingest / a
//                   multi-step orchestrated flow).
// ---------------------------------------------------------------------------
const FOUR_CLASSES = Object.freeze(['mechanical', 'framework', 'intelligence', 'pipeline']);
const CLASS_UTILITY_EXCLUDED = 'utility-excluded';

// Phase 235-02 (CIRS-02). The MCP-tool-FILE class: an ADDITIVE fifth member of
// the class enum, deliberately NOT one of the four governance classes. An MCP
// tool file is a module-liveness surface (does it load and export usable
// connectors?), not a pws methodology / plumbing / engine / pipeline surface, so
// it sits alongside CLASS_UTILITY_EXCLUDED rather than inside FOUR_CLASSES.
// tests/test-cirs-four-class-floor.cjs deliberately never asserts a class COUNT
// (see its header) precisely so an additive member like this one cannot
// false-fail the floor.
const CLASS_MCP_TOOL = 'mcp_tool';
const SURFACE_CLASS_ENUM = Object.freeze(
  FOUR_CLASSES.concat([CLASS_UTILITY_EXCLUDED, CLASS_MCP_TOOL])
);

// The intelligence-surface name prefixes/markers (engine/sensor/analysis). A
// surface whose base matches one of these is an intelligence class. Generic
// machinery handles only (Part 8).
const INTELLIGENCE_MARKERS = Object.freeze([
  'rs-', 'find-', 'score-', 'whitespace', 'diagnostics', 'radar',
  'breakthrough', 'reverse-salient', 'analyze-', 'detect-',
  'intelligence-orchestrator', 'lens', 'sensor',
]);

// The pipeline-surface name markers (chain/workflow). A multi-step orchestrated
// flow.
const PIPELINE_MARKERS = Object.freeze([
  'act', 'discover', 'ingest', 'pipeline', 'chain', 'workflow', 'run-chain', 'runchain',
]);

// ---------------------------------------------------------------------------
// classifySurfaceClass(src, fm, state) -- derive the one governed class for a
// surface (Canon Part 11 R1 four-class amendment). EXCLUDED surfaces take the
// `utility-excluded` slot. Otherwise: a surface that declares a frameworks:
// block or a resolvable connector.framework is `framework`; an intelligence
// marker base is `intelligence`; a pipeline marker base is `pipeline`;
// everything else is `mechanical`. Deterministic + pure (reads only the passed
// frontmatter + base name). The order is framework -> pipeline -> intelligence
// -> mechanical so an act-like pipeline that also declares a framework is named
// by its strongest signal (framework methodology wins). Zero Brain/network.
// ---------------------------------------------------------------------------
function classifySurfaceClass(src, fm, state) {
  if (state === 'excluded') return CLASS_UTILITY_EXCLUDED;
  const base = (src && typeof src.base === 'string') ? src.base.toLowerCase() : '';
  const conn = fm && fm.connector && typeof fm.connector === 'object' && !Array.isArray(fm.connector)
    ? fm.connector
    : null;
  const hasFrameworksBlock = Array.isArray(fm && fm.frameworks) && fm.frameworks.length > 0;
  const hasConnFramework =
    conn && typeof conn.framework === 'string' && conn.framework.trim().length > 0;
  if (hasFrameworksBlock || hasConnFramework) return 'framework';
  if (PIPELINE_MARKERS.indexOf(base) !== -1) return 'pipeline';
  if (INTELLIGENCE_MARKERS.some(function (m) { return base.indexOf(m) === 0 || base === m; })) {
    return 'intelligence';
  }
  return 'mechanical';
}

// classifySurface(src) -- the pure per-surface classifier shared by
// coverageReport(). Reads ONE source file's connector frontmatter and returns
// the R1 (Canon Part 11) terminal state:
//   - 'wired'    : connector.connects_to_spine === true
//   - 'excluded' : connector.excluded === true (a reason is REQUIRED; a missing
//                  reason is a build error reported via the `error` field)
//   - 'gap'      : neither (the surface is dark)
// `excluded` takes precedence over a stray connects_to_spine on the same block:
// an EXCLUDED surface is never counted as a gap. Returns
// { surface, source, state, reason?, error? }. Zero Brain, zero network.
// ---------------------------------------------------------------------------
function classifySurface(src) {
  const surfaceName =
    src.kind === 'command'
      ? '/mos:' + src.base
      : src.kind === 'skill'
        ? 'skill:' + src.base
        : 'agent:' + src.base;

  let fm;
  try {
    fm = parseConnectorFrontmatter(fs.readFileSync(src.file, 'utf8'));
  } catch (_e) {
    fm = {};
  }
  const conn = fm.connector;
  const hasConn = conn && typeof conn === 'object' && !Array.isArray(conn);

  if (hasConn && conn.excluded === true) {
    const reason =
      typeof conn.reason === 'string' && conn.reason.trim() ? conn.reason.trim() : null;
    const out = {
      surface: surfaceName,
      source: src.kind,
      state: 'excluded',
      reason,
      class: classifySurfaceClass(src, fm, 'excluded'),
    };
    if (!reason) {
      out.error =
        'connector ' + surfaceName +
        ' declares excluded:true but no reason (D-172-a: no surface dark by accident)';
    }
    return out;
  }

  if (hasConn && conn.connects_to_spine === true) {
    return {
      surface: surfaceName,
      source: src.kind,
      state: 'wired',
      class: classifySurfaceClass(src, fm, 'wired'),
    };
  }

  return {
    surface: surfaceName,
    source: src.kind,
    state: 'gap',
    class: classifySurfaceClass(src, fm, 'gap'),
  };
}

// ---------------------------------------------------------------------------
// coverageReport() -- the wired-XOR-excluded coverage classifier (Canon Part 11
// R1/R9). Walks EVERY surface listSourceFiles() walks and classifies each as
// wired / excluded / gap, so the command+skill+agent slice of surfaces.length
// === the total command+skill+agent file count. Phase 235-02 adds a SECOND
// slice: one surface per claimed MCP tool file (source:'mcp_tool'), so
// surfaces.length === listSourceFiles().length + listMcpToolClaimedSources()
// .length. counts.wired + counts.excluded + counts.gap === surfaces.length
// either way (the XOR invariant: every surface lands in exactly one bucket).
// Returns
// { surfaces: [{surface, source, state}], counts: {wired, excluded, gap},
//   errors: [...] } where errors carries any excluded-without-reason build
// error. Pure: reads only the source frontmatter, makes ZERO Brain/network
// calls, opens NO Brain wire (Part 8). This is the R9 gate's source of truth.
// ---------------------------------------------------------------------------
function coverageReport() {
  const surfaces = [];
  const counts = { wired: 0, excluded: 0, gap: 0 };
  const errors = [];
  for (const src of listSourceFiles()) {
    const c = classifySurface(src);
    surfaces.push({ surface: c.surface, source: c.source, state: c.state, class: c.class });
    counts[c.state] += 1;
    if (c.error) errors.push(c.error);
  }

  // Phase 235-02 (CIRS-02): the MCP-tool-file walk. Before this, MCP tools sat
  // entirely outside the wired-XOR-excluded invariant -- coverageReport() walked
  // only listSourceFiles(), and the separate listMcpToolConnectorDescriptors()
  // path silently swallowed both a require() failure and a missing/empty
  // `connectors` export. A tool file could be born dark and the gate stayed
  // green. Every claimed source is now a surface here, so main()'s existing
  // generic `state === 'gap'` hard-fail catches a dead one with no change to
  // main() itself. The dead/live decision is delegated to the SHARED
  // seam-liveness helper, never reimplemented inline: this call is load-bearing
  // and tests/test-235-seam-liveness-mcp-coverage.cjs proves it.
  const mcpHealth = listMcpToolFileHealth();
  const mcpLiveness = seamLiveness.checkClaimedModuleLiveness(
    mcpHealth.map((h) => ({
      id: h.id,
      live: h.live,
      reason: h.loadError || 'exports.' + h.exportKey + ' is missing or empty',
    }))
  );
  const mcpDead = new Set(mcpLiveness.dead);
  for (const h of mcpHealth) {
    const state = mcpDead.has(h.id) ? 'gap' : 'wired';
    surfaces.push({
      surface: 'mcp_tool_file:' + h.id,
      source: 'mcp_tool',
      state,
      class: CLASS_MCP_TOOL,
    });
    counts[state] += 1;
  }

  surfaces.sort((a, b) => a.surface.localeCompare(b.surface));
  return { surfaces, counts, errors };
}

// ---------------------------------------------------------------------------
// serializeLedger(report) -- emit data/connector-coverage-ledger.json from a
// coverageReport() result. Top-level keys are EXACTLY generated_note, counts,
// surfaces (surfaces sorted by surface name for determinism). Mirrors
// serializeRegistry's JSON.stringify(...,2) + trailing-newline + byte-compare
// discipline so the --check STALE byte-compare is deterministic. The non-
// serialized `errors` field never lands on disk.
// ---------------------------------------------------------------------------
function serializeLedger(report) {
  const surfaces = Array.isArray(report && report.surfaces)
    ? report.surfaces
        .slice()
        .map((s) => ({ surface: s.surface, source: s.source, state: s.state, class: s.class }))
        .sort((a, b) => a.surface.localeCompare(b.surface))
    : [];
  const counts =
    report && report.counts
      ? { wired: report.counts.wired, excluded: report.counts.excluded, gap: report.counts.gap }
      : { wired: 0, excluded: 0, gap: 0 };
  const clean = {
    generated_note: LEDGER_GENERATED_NOTE,
    counts,
    surfaces,
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// validateConnectors(reg) -- the four CONN-03 validations. Returns an array of
// error strings (empty = clean). Pure: reads only the built registry + the two
// frozen banks + the resolver (zero Brain, zero network). Exported so
// tests/test-connector-tripwire.cjs can exercise each bad case directly without
// spawning a subprocess.
//
// The four validations (mirroring the missingTeaching error in
// build-command-registry.cjs lines 367-382):
//   (1) every reach_id is one of the frozen 6 (REACH_IDS)
//   (2) every framework resolves via commandsForFramework() (WFL-01) -- checked
//       for connectors that declare a filing or a decision surface (the ones
//       that actually fire a command on APPROVE)
//   (3) every posture is one of the frozen 3 (POSTURE_IDS)
//   (4) no duplicate (sensor, reach, sub_mode) tuple collision
// ---------------------------------------------------------------------------
function validateConnectors(reg) {
  const errs = [];
  const connectors = Array.isArray(reg && reg.connectors) ? reg.connectors : [];
  const seenTuples = new Set();

  for (const c of connectors) {
    const surface = (c && c.surface) || (c && c.command) || '<unknown>';

    // Phase 198-04 (SPEC-2, Task 1): an MCP-tool connector (source:'mcp_tool')
    // is governed by the hitl_shape/hitl_why dial, not reach_id/posture -- it
    // legitimately carries reach_id:null/posture:null (normalizeMcpToolEntry
    // above). The frozen-6/frozen-3 checks below are scoped to the
    // reach/posture dial (commands/skills/agents); an MCP tool's hitl_shape is
    // validated separately, advisory, by scripts/check-shape-declaration.cjs's
    // MCP-tool enumeration -- never here, and never a hard --check failure.
    const isMcpTool = c && c.source === 'mcp_tool';

    // (1) frozen-6 reach.
    if (!isMcpTool && REACH_IDS.indexOf(c && c.reach_id) === -1) {
      errs.push(
        'connector ' + surface + ' reach_id ' + (c && c.reach_id) +
          ' not in frozen 6'
      );
    }

    // (3) frozen-3 posture.
    if (!isMcpTool && POSTURE_IDS.indexOf(c && c.posture) === -1) {
      errs.push(
        'connector ' + surface + ' posture ' + (c && c.posture) +
          ' not in frozen 3'
      );
    }

    // (2) WFL-01 resolver-resolution: a connector that declares a filing or a
    // decision surface AND DECLARES A FRAMEWORK fires a command on APPROVE via
    // framework resolution, so that framework MUST resolve through
    // commandsForFramework(). A connector with framework:null declares no
    // framework -- per CONNECTOR-CONTRACT.md section 4 (additive-degrade) it
    // routes through the orchestrator with no framework and degrades to "run it
    // manually" rather than fabricating a command. The minimal Part-8-safe
    // memory-cortex reach (Phase 150, framework:null + filing:memory_event_only)
    // is exactly this degrade case; gating the resolver check on a declared
    // framework keeps the additive-degrade rule honest.
    const declaresFramework = typeof c.framework === 'string' && c.framework;
    const firesCommand =
      ((typeof c.filing === 'string' && c.filing && c.filing !== 'none') ||
        (typeof c.decision_surface === 'string' && c.decision_surface)) &&
      declaresFramework;
    if (firesCommand) {
      const resolved = commandsForFramework(c && c.framework);
      if (!Array.isArray(resolved) || resolved.length === 0) {
        errs.push(
          'connector ' + surface + ' framework ' +
            JSON.stringify(c && c.framework) +
            ' does not resolve via commandsForFramework (WFL-01)'
        );
      }
    }

    // (4) no duplicate (sensor, reach, sub_mode) tuple. score-innovation and
    // whitespace share SENS-06 + context_block but differ in sub_mode (hsi vs
    // whitespace) -- a legal distinct tuple. A genuine collision (same sensor +
    // reach + sub_mode on two surfaces) fails.
    const sensors = Array.isArray(c && c.sensor_triggers) ? c.sensor_triggers : [];
    const reach = c && c.reach_id;
    const subMode = c && c.sub_mode;
    for (const sid of sensors) {
      const tuple = sid + '|' + reach + '|' + subMode;
      if (seenTuples.has(tuple)) {
        errs.push(
          'duplicate connector tuple (sensor,reach,sub_mode): ' + tuple +
            ' (surface ' + surface + ')'
        );
      } else {
        seenTuples.add(tuple);
      }
    }
  }

  return errs;
}

// ---------------------------------------------------------------------------
// methodologyCommandsMissingConnector() -- the WARN nudge source. A command
// whose frontmatter carries a `frameworks:` block (the methodology heuristic,
// mirroring build-command-registry.cjs's kind/frameworks signal) but NO
// `connector:` block has not opted into the spine. This is a STDERR WARNING
// (opt-in nudge), NEVER a hard fail -- mirroring the missingServesJtbd WARNING
// at build-command-registry.cjs lines 406-417.
// ---------------------------------------------------------------------------
function methodologyCommandsMissingConnector() {
  const out = [];
  let cmdFiles = [];
  try {
    cmdFiles = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    cmdFiles = [];
  }
  for (const f of cmdFiles) {
    let fm;
    try {
      fm = parseConnectorFrontmatter(fs.readFileSync(path.join(COMMANDS_DIR, f), 'utf8'));
    } catch (_e) {
      continue;
    }
    const hasFrameworks =
      Array.isArray(fm.frameworks) && fm.frameworks.length > 0;
    const hasConnector =
      fm.connector && typeof fm.connector === 'object' && !Array.isArray(fm.connector);
    if (hasFrameworks && !hasConnector) {
      out.push('/mos:' + f.replace(/\.md$/, ''));
    }
  }
  return out;
}

