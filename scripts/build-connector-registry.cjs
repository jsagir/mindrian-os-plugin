// dead seam.
//
// Returns [{ id, path, exportKey }] -- one entry per lib/mcp/tools/*.cjs file
// (sorted, deterministic), plus lib/mcp/tool-router.cjs (MCP_TOOL_CONNECTORS)
// and lib/mcp/contract-version.cjs (connectors) when they exist. Pure
