#!/usr/bin/env node
'use strict';

/*
 * Phase 143.3-01 - Connector registry generator + drift tripwire + names refresh.
 *
 * Implements: CONN-02 (the generator with the nested-map parser extension).
 *
 * The Connector Contract generalizes Phase 122: the `connector:` frontmatter
 * block on each skill/command is the ONE place the reach-wiring lives, and
 * `data/connector-registry.json` is GENERATED from it and CI-checked against it.
 * A `--check` run regenerates it in memory and exits non-zero on a stale
 * on-disk registry OR an unresolvable framework name (one not in the
 * FEEDS_INTO-linked Brain framework slice snapshotted to
 * `data/framework-names.json`).
 *
 * Canon Part 7 (Reuse Before Build): this MIRRORS
 * scripts/build-command-registry.cjs wholesale -- the hand-rolled line-walk
 * frontmatter parser, the static-allowlist load, the deterministic serializer,
 * the three-branch main(). The ONE genuine net-new concern is the nested-map
 * descent (parseConnectorFrontmatter), because the `connector:` block is one
 * indent level deeper than Phase 122's flat `frameworks:` list. It adds NO new
 * dependency (no gray-matter, no zod).
 *
 * Canon Part 8 (The Graph Boundary): the registry is plugin-local, validated
 * AGAINST the SHIPPED Brain framework-name snapshot, NEVER written back. The
 * ONLY Brain touch is a read-only brain.query in --refresh-names at BUILD time
 * -- the query carries only generic `:Framework` node names (a methodology
 * handle, never user data), and there is no write Cypher anywhere in this file.
 * A connector's framework/web_scope are GENERIC handles only; the registry
 * never carries user content. The generator and the orchestrator never need the
 * Brain at runtime.
 *
 * Usage:
 *   node scripts/build-connector-registry.cjs
 *       scan the commands and skills frontmatter -> write
 *       data/connector-registry.json ; exit 1 on an unresolvable framework
 *   node scripts/build-connector-registry.cjs --check
 *       regenerate in memory ; exit 1 if on-disk JSON is stale OR a framework
 *       is unresolvable ; print a one-line recovery command in stderr
 *   node scripts/build-connector-registry.cjs --refresh-names
 *       read-only brain.query -> rewrite data/framework-names.json
 *       (build-time only ; graceful no-op if the Brain is unreachable)
 */

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const COMMANDS_DIR = path.join(REPO_ROOT, 'commands');
const SKILLS_DIR = path.join(REPO_ROOT, 'skills');
const DATA_DIR = path.join(REPO_ROOT, 'data');
const REGISTRY_PATH = path.join(DATA_DIR, 'connector-registry.json');
const FW_NAMES_PATH = path.join(DATA_DIR, 'framework-names.json');

const GENERATED_NOTE =
  'GENERATED by scripts/build-connector-registry.cjs - do not edit by hand';

// The FEEDS_INTO traversal that snapshots the framework-name allowlist. This
// is the ONLY Cypher this file ever runs, it is read-only, and it carries no
// user-specific strings -- only the generic `:Framework` label. Reused from
// build-command-registry.cjs verbatim so a --refresh-names here matches Phase
// 122 exactly.
const FW_NAMES_CYPHER =
  'MATCH (f:Framework) WHERE (f)-[:FEEDS_INTO]-() RETURN f.name AS name';

// The 11 connector sub-keys (the contract in docs/CONNECTOR-CONTRACT.md). The
// generator pulls each from the parsed connector map; absent fields degrade.
const CONNECTOR_KEYS = [
  'connects_to_spine',
  'sensor_triggers',
  'reach_id',
  'sub_mode',
  'framework',
  'posture',
  'hierarchy_rank',
  'filing',
  'plan_gated',
  'web_scope',
  'surface',
];

// ---------------------------------------------------------------------------
// coerce(v) -- the value coercions the flat parser already does (null, boolean,
// integer, JSON array, quote-strip). Shared by the flat top-level walk and the
// nested connector descent so the two stay byte-identical in behavior.
// ---------------------------------------------------------------------------
function coerce(v) {
  if (v === '') return [];
  if (v === 'null' || v === '~') return null;
  if (v === 'true' || v === 'false') return v === 'true';
  if (/^-?\d+$/.test(v)) return parseInt(v, 10);
  if (v.startsWith('[')) {
    try {
      return JSON.parse(v);
    } catch (_e) {
      // Not strict JSON (e.g. `[SENS-02, SENS-07]` with unquoted tokens, the
      // common shape for sensor_triggers). Split the inner CSV into a trimmed,
      // quote-stripped array. An empty `[]` yields [].
      const inner = v.replace(/^\[/, '').replace(/\]$/, '').trim();
      if (inner === '') return [];
      return inner
        .split(',')
        .map((s) => s.trim().replace(/^["']|["']$/g, ''))
        .filter((s) => s.length > 0);
    }
  }
  return v.replace(/^["']|["']$/g, '');
}

// ---------------------------------------------------------------------------
// parseConnectorFrontmatter(md) -- the nested-map parser. Mirrors the flat
// parseFrontmatter in build-command-registry.cjs (lines 100-137) AND extends it
// to DESCEND one indent level into the `connector:` nested map: when a
// top-level key is `connector` with an empty value, subsequent indented
// `  key: value` lines are accumulated into out.connector as an object, with
// the SAME value coercions (null, booleans, integers, JSON arrays, indented
// dash-lists, quote-stripping). This nested descent is the ONE genuine net-new
// parsing concern this phase introduces.
// ---------------------------------------------------------------------------
function parseConnectorFrontmatter(md) {
  if (typeof md !== 'string') return {};
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md);
  if (!m) return {};
  const out = {};
  let key = null; // current top-level dash-list key

  // Nested-descent state: when we are inside the `connector:` map, every
  // indented line is parsed into `connectorObj` until a non-indented line ends
  // the block.
  let inConnector = false;
  let connectorObj = null;
  let connectorKey = null; // current nested dash-list key

  for (const rawLine of m[1].split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    const indented = /^\s+\S/.test(line);

    // While inside the connector map, an indented line is a nested sub-key (or a
    // nested dash-list item). A non-indented, non-blank line ends the block.
    if (inConnector) {
      if (line.trim() === '' || indented) {
        if (line.trim() === '') continue;
        // Strip the comment-only lines (e.g. `  # MUST match ...`).
        const noComment = line.replace(/\s+#.*$/, '');
        const subKv = /^\s+([A-Za-z0-9_-]+):\s*(.*)$/.exec(noComment);
        if (subKv) {
          connectorKey = subKv[1];
          const sv = subKv[2].trim();
          connectorObj[connectorKey] = coerce(sv);
          continue;
        }
        const subDash = /^\s+-\s+(.*)$/.exec(noComment);
        if (subDash && connectorKey) {
          if (!Array.isArray(connectorObj[connectorKey])) connectorObj[connectorKey] = [];
          connectorObj[connectorKey].push(subDash[1].replace(/^["']|["']$/g, ''));
          continue;
        }
        // An indented line that is neither (blank-after-trim handled above) is
        // ignored.
        continue;
      }
      // A non-indented line -> the connector block is done.
      inConnector = false;
      out.connector = connectorObj;
      connectorObj = null;
      connectorKey = null;
      // fall through to parse this line as a normal top-level line
    }

    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (kv) {
      key = kv[1];
      const v = kv[2].trim();
      if (key === 'connector' && v === '') {
        // Enter the nested descent. connectorObj accumulates the sub-keys.
        inConnector = true;
        connectorObj = {};
        connectorKey = null;
        continue;
      }
      out[key] = coerce(v);
    } else if (key && /^\s*-\s+/.test(line)) {
      if (!Array.isArray(out[key])) out[key] = [];
      out[key].push(line.replace(/^\s*-\s+/, '').replace(/^["']|["']$/g, ''));
    }
    // Any other line (blank, comment `# ...`) is ignored.
  }

  // EOF inside the connector block -> flush it.
  if (inConnector && connectorObj) out.connector = connectorObj;

  return out;
}

// ---------------------------------------------------------------------------
// Load the committed framework-name allowlist (the FEEDS_INTO-linked Brain
// slice UNION curated_extras). Mirrors build-command-registry.cjs verbatim --
// the connector generator REUSES the shipped data/framework-names.json; it adds
// NO new Brain query.
// ---------------------------------------------------------------------------
function loadFrameworkNames() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const names = Array.isArray(raw && raw.framework_names) ? raw.framework_names : [];
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return new Set([...names, ...extras]);
  } catch (_e) {
    return new Set();
  }
}

function loadCuratedExtras() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return extras.slice();
  } catch (_e) {
    return [];
  }
}

// ---------------------------------------------------------------------------
// Source-file discovery: walk BOTH commands/*.md AND skills/*/SKILL.md,
// deterministically sorted, so the registry is byte-stable across machines.
// Returns [{ surface, file }] where `surface` is the registry id.
// ---------------------------------------------------------------------------
function listSourceFiles() {
  const out = [];

  let cmdFiles = [];
  try {
    cmdFiles = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.md')).sort();
  } catch (_e) {
    cmdFiles = [];
  }
  for (const f of cmdFiles) {
    out.push({ kind: 'command', file: path.join(COMMANDS_DIR, f), base: f.replace(/\.md$/, '') });
  }

  let skillDirs = [];
  try {
    skillDirs = fs
      .readdirSync(SKILLS_DIR, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();
  } catch (_e) {
    skillDirs = [];
  }
  for (const d of skillDirs) {
    const skillFile = path.join(SKILLS_DIR, d, 'SKILL.md');
    if (fs.existsSync(skillFile)) {
      out.push({ kind: 'skill', file: skillFile, base: d });
    }
  }

  return out;
}

// ---------------------------------------------------------------------------
// buildRegistry() -- walk commands + skills (sorted), parse the nested
// connector map, filter to surfaces where connector.connects_to_spine === true,
// build the connectors[] array, the sensor_index, the framework_index, and
// collect _unresolved for any framework not in the allowlist. Returns the
// registry object PLUS the non-serialized `_unresolved` field (callers strip it
// before writing).
// ---------------------------------------------------------------------------
function buildRegistry() {
  const fwNames = loadFrameworkNames();
  const sources = listSourceFiles();
  const connectors = [];
  const sensorIndex = {};
  const frameworkIndex = {};
  const unresolved = [];

  for (const src of sources) {
    let fm;
    try {
      fm = parseConnectorFrontmatter(fs.readFileSync(src.file, 'utf8'));
    } catch (_e) {
      continue;
    }
    const conn = fm.connector;
    if (!conn || typeof conn !== 'object' || Array.isArray(conn)) continue;
    // Filter: only surfaces that opt in are wired. Absent/false = legacy.
    if (conn.connects_to_spine !== true) continue;

    const surfaceName =
      src.kind === 'command' ? '/mos:' + src.base : 'skill:' + src.base;

    const sensorTriggers = Array.isArray(conn.sensor_triggers)
      ? conn.sensor_triggers.slice()
      : [];
    const framework =
      typeof conn.framework === 'string' && conn.framework ? conn.framework : null;

    const entry = {
      surface: surfaceName,
      source: src.kind,
      connects_to_spine: true,
      sensor_triggers: sensorTriggers,
      reach_id: typeof conn.reach_id === 'string' ? conn.reach_id : null,
      sub_mode: typeof conn.sub_mode === 'string' ? conn.sub_mode : null,
      framework,
      posture: typeof conn.posture === 'string' ? conn.posture : null,
      hierarchy_rank:
        typeof conn.hierarchy_rank === 'number' ? conn.hierarchy_rank : null,
      filing: typeof conn.filing === 'string' ? conn.filing : null,
      plan_gated: conn.plan_gated === true,
      web_scope:
        typeof conn.web_scope === 'string' && conn.web_scope ? conn.web_scope : null,
      decision_surface: typeof conn.surface === 'string' ? conn.surface : null,
    };

    // WFL-01 build-time guard (mirror build-command-registry.cjs line 222):
    // a framework not in the allowlist is unresolvable.
    if (framework && !fwNames.has(framework)) {
      unresolved.push({ surface: surfaceName, framework });
    }

    // sensor_index: each sensor_id -> push this connector's surface.
    for (const sid of sensorTriggers) {
      if (!Array.isArray(sensorIndex[sid])) sensorIndex[sid] = [];
      sensorIndex[sid].push(surfaceName);
    }

    // framework_index: framework -> [surface] (the Phase 122 inverse-index idiom).
    if (framework) {
      if (!Array.isArray(frameworkIndex[framework])) frameworkIndex[framework] = [];
      frameworkIndex[framework].push(surfaceName);
    }

    connectors.push(entry);
  }

  return {
    ontology_ref: 'data/framework-names.json',
    generated_note: GENERATED_NOTE,
    connectors,
    sensor_index: sensorIndex,
    framework_index: frameworkIndex,
    _unresolved: unresolved,
  };
}

// Serialize the registry exactly the way the on-disk file is written, so the
// --check byte-compare is deterministic. Strips the non-serialized
// `_unresolved` field. (Copied from build-command-registry.cjs lines 256-265 in
// spirit so the layout + trailing newline are stable.)
function serializeRegistry(reg) {
  const clean = {
    ontology_ref: reg.ontology_ref,
    generated_note: reg.generated_note,
    connectors: reg.connectors,
    sensor_index: reg.sensor_index,
    framework_index: reg.framework_index,
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// --refresh-names: read-only brain.query for the FEEDS_INTO-linked name
// slice -> rewrite data/framework-names.json. BUILD-TIME ONLY. The ONLY code
// path in this file that touches the Brain, and it is read-only. brain-client
// is required HERE -- inside this branch only. There is no top-level require of
// brain-client; the generator and --check never load it.
// ---------------------------------------------------------------------------
async function refreshNames() {
  let brain;
  try {
    brain = require(path.join(REPO_ROOT, 'lib', 'core', 'brain-client.cjs'));
  } catch (_e) {
    console.error('Brain client unavailable -- keeping the committed snapshot');
    process.exit(0);
    return;
  }
  if (!brain.isAvailable || !brain.isAvailable()) {
    console.log('Brain unavailable -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  let result;
  try {
    result = await brain.query(FW_NAMES_CYPHER);
  } catch (_e) {
    console.log('Brain query failed -- keeping the committed snapshot');
    process.exit(0);
    return;
  }
  if (!result || !Array.isArray(result.records)) {
    console.log('Brain returned no usable records -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  const names = [];
  for (const rec of result.records) {
    const v = rec && (rec.name !== undefined ? rec.name : rec['f.name']);
    if (typeof v === 'string' && v.trim()) names.push(v.trim());
  }
  const deduped = Array.from(new Set(names)).sort((a, b) => a.localeCompare(b));
  if (deduped.length === 0) {
    console.log('Brain returned an empty name list -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  const curatedExtras = loadCuratedExtras().slice().sort((a, b) => a.localeCompare(b));
  const snapshot = {
    snapshot_note:
      'FEEDS_INTO-linked :Framework names from the Brain (read-only build-time query). Refresh with: node scripts/build-command-registry.cjs --refresh-names',
    snapshot_date: new Date().toISOString().slice(0, 10),
    framework_names: deduped,
    curated_extras_note:
      'Legitimate :Framework node names that exist in the Brain but are not yet FEEDS_INTO-linked. Hand-curated. NOT junk nodes. The allowlist the registry validates against is framework_names UNION curated_extras.',
    curated_extras: curatedExtras,
  };
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(FW_NAMES_PATH, JSON.stringify(snapshot, null, 2) + '\n');
  console.log('Wrote data/framework-names.json (' + deduped.length + ' FEEDS_INTO-linked names)');
}

// ---------------------------------------------------------------------------
// main()
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--refresh-names')) {
    refreshNames().catch((e) => {
      console.error('refresh-names error: ' + (e && e.message ? e.message : String(e)));
      process.exit(1);
    });
    return;
  }

  const reg = buildRegistry();
  const errs = [];
  if (reg._unresolved.length) {
    const list = reg._unresolved
      .map((u) => u.surface + ' -> "' + u.framework + '"')
      .join(', ');
    errs.push('Unresolvable frameworks (not in data/framework-names.json): ' + list);
  }

  if (argv.includes('--check')) {
    const next = serializeRegistry(reg);
    const onDisk = fs.existsSync(REGISTRY_PATH) ? fs.readFileSync(REGISTRY_PATH, 'utf8') : '';
    if (onDisk !== next) {
      errs.push('data/connector-registry.json is STALE. Run: node scripts/build-connector-registry.cjs');
    }
    if (errs.length) {
      console.error(errs.join('\n'));
      console.error('Recovery: fix the connector frontmatter (or run --refresh-names), then regenerate: node scripts/build-connector-registry.cjs');
      process.exit(1);
    }
    console.log('connector-registry: OK');
    return;
  }

  // Default: write the registry, refusing on any unresolvable framework.
  if (errs.length) {
    console.error(errs.join('\n'));
    console.error('Recovery: fix the connector frontmatter (or run --refresh-names), then re-run: node scripts/build-connector-registry.cjs');
    process.exit(1);
  }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(REGISTRY_PATH, serializeRegistry(reg));
  console.log('Wrote data/connector-registry.json (' + reg.connectors.length + ' connectors)');
}

if (require.main === module) {
  main();
} else {
  module.exports = { parseConnectorFrontmatter, buildRegistry, serializeRegistry };
}
