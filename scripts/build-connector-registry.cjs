    if (onDisk !== next) {
      errs.push('data/connector-registry.json is STALE. Run: node scripts/build-connector-registry.cjs');
    }

    // The coverage ledger STALE byte-compare (same discipline as the registry).
    // Regenerate the ledger in memory and fail if the on-disk ledger drifts.
