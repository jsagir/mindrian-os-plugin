'use strict';

/*
 * Copyright (c) 2026 Mindrian. BSL 1.1.
 * Phase 95.1 D2 -- ROOM.md / MINTO.md generator for class E remediation.
 *
 * Default scope: ONE directory. With --recursive, walks the subtree.
 * Idempotent: skip if file exists; --force overrides.
 * Hand-rolled minimal frontmatter per D-03 (NOT imported from
 * vault-section-{state,minto}-generator.cjs).
 *
 * MODES:
 *   generate-section-intelligence.cjs <dir>                 single dir
 *   generate-section-intelligence.cjs <dir> --recursive     subtree
 *   generate-section-intelligence.cjs <dir> --force         overwrite
 *   generate-section-intelligence.cjs --help                usage
 *
 * Exit codes:
 *   0  -> success (files created or skipped per D-02)
 *   1  -> generation failed (one or more directories errored, or anchor missing)
 *   2  -> usage error (no positional arg, unknown flag)
 *
 * Phase 95.1 scope. See .planning/phases/95.1-mos-doctor-drift-detection-and-self-heal/
 * 95.1-CONTEXT.md decisions D-01..D-03.
 *
 * Output frontmatter satisfies Phase 87-01a's pre-commit guard expectation
 * (section + license fields present in both files; license = BSL-1.1 by
 * default). The generator itself never overwrites a user-edited ROOM.md or
 * MINTO.md unless --force is passed -- D-02 is non-negotiable so that
 * downstream cascade tooling can rerun this script safely on a populated room.
 *
 * Atomic write contract per Phase 95-02: target files are written via
 * mktemp + fs.renameSync(2) on the same filesystem so concurrent Cowork
 * sessions never observe a torn write. This mirrors scripts/post-write
 * write_cascade_side_channel (lines 90-126) -- the canonical bash pattern
 * ported to CJS.
 *
 * UI Ruling System §3 vocabulary: only the 12 approved glyphs are emitted
 * in user-facing output (`✓` for wrote, `⬜` for skipped, `⚠` for warnings).
 * No box chars. No cross-mark glyph. No emoji. SKILL.md §4 colors are not applied here
 * because this script is a tool surface (not a Shape E renderer); plain
 * stdout/stderr is sufficient.
 */

const fs = require('fs');
const path = require('path');

// ── Constants ────────────────────────────────────────────────────────

const SKIP_DIRS = new Set([
  '.git',
  '.mindrian',
  '.context',
  '.lazygraph',
  '.rooms',
  'node_modules',
  '.next',
  'dist',
  'build',
  '.cache',
]);
// Mirror detect_room_section's hop cap (scripts/post-write line 30).
const MAX_DEPTH = 12;
const DEFAULT_LICENSE = 'BSL-1.1';

// ── Argument parsing ─────────────────────────────────────────────────

function parseArgs(argv) {
  const flags = { recursive: false, force: false, help: false };
  const positional = [];
  let unknown = null;
  for (const arg of argv) {
    if (arg === '--recursive' || arg === '-r') flags.recursive = true;
    else if (arg === '--force' || arg === '-f') flags.force = true;
    else if (arg === '--help' || arg === '-h') flags.help = true;
    else if (arg.startsWith('--') || (arg.startsWith('-') && arg.length > 1 && arg !== '-')) {
      unknown = arg;
      break;
    } else positional.push(arg);
  }
  return { flags, positional, unknown };
}

function usageText() {
  return [
    'Usage: generate-section-intelligence.cjs <dir> [--recursive] [--force]',
    '',
    '  <dir>            single dir mode -- generate ROOM.md + MINTO.md in <dir>',
    '  --recursive, -r  walk the subtree under <dir>; generate per directory',
    '  --force,     -f  overwrite existing ROOM.md / MINTO.md (default: skip)',
    '  --help,      -h  print this help and exit',
    '',
    'Hand-rolled minimal frontmatter (Phase 95.1 D-03). Skipped dirs:',
    '  ' + Array.from(SKIP_DIRS).join(', '),
    '',
    'Exit codes:',
    '  0  success (files created or skipped per D-02)',
    '  1  generation failed (anchor missing or per-directory error)',
    '  2  usage error (no positional arg, unknown flag)',
  ].join('\n');
}

// ── Frontmatter templates (D-03 hand-rolled) ─────────────────────────

function roomMdTemplate(opts) {
  const section = opts.section;
  const parent = opts.parent;
  const dateIso = opts.dateIso;
  const license = opts.license || DEFAULT_LICENSE;
  return [
    '---',
    'section: ' + section,
    'parent: ' + parent,
    'created: ' + dateIso,
    'license: ' + license,
    '---',
    '',
    '# ' + section,
    '',
    '(Section identity. Generated by /mos:doctor --fix --room-md or directly by',
    'scripts/generate-section-intelligence.cjs. Edit freely -- the generator will',
    'not overwrite an existing file unless --force is passed.)',
    '',
  ].join('\n');
}

function mintoMdTemplate(opts) {
  const section = opts.section;
  const dateIso = opts.dateIso;
  const license = opts.license || DEFAULT_LICENSE;
  const gt = opts.governingThought ||
    'TBD -- fill in the one-sentence governing thought.';
  return [
    '---',
    'type: section-minto',
    'section: ' + section,
    'governing_thought: ' + gt,
    'created: ' + dateIso,
    'license: ' + license,
    '---',
    '',
    '# Governing Thought',
    '',
    gt,
    '',
    '## MECE Support',
    '',
    '1. (Add 2+ MECE-supporting points to satisfy Phase 81 Feynman-MINTO contract.)',
    '2. ',
    '3. ',
    '',
  ].join('\n');
}

// ── Atomic write (Phase 95-02 invariant) ─────────────────────────────

function atomicWrite(targetPath, content) {
  const dir = path.dirname(targetPath);
  fs.mkdirSync(dir, { recursive: true });
  // Same-filesystem invariant: tmp lives in same dir as target so that
  // rename(2) is atomic on POSIX. The .tmp.<pid> suffix keeps the test
  // matcher happy (test-generate-section-intelligence.cjs Test 5 lists
  // leaks via /\.(?:ROOM|MINTO)\.md\.tmp\.\d+$/).
  const tmp = path.join(
    dir,
    '.' + path.basename(targetPath) + '.tmp.' + process.pid
  );
  try {
    fs.writeFileSync(tmp, content);
    fs.renameSync(tmp, targetPath);
  } catch (err) {
    // Best-effort cleanup; do not mask the original error.
    try { fs.unlinkSync(tmp); } catch (_) { /* ignore */ }
    throw err;
  }
}

// ── Per-directory generation ─────────────────────────────────────────

function generateForDir(dirPath, options) {
  const force = !!(options && options.force);
  const result = { wrote: [], skipped: [], errors: [] };

  let stat;
  try {
    stat = fs.statSync(dirPath);
  } catch (err) {
    result.errors.push({ path: dirPath, message: err.message });
    return result;
  }
  if (!stat.isDirectory()) {
    result.errors.push({ path: dirPath, message: 'not a directory' });
    return result;
  }

  const section = path.basename(dirPath);
  const parent = path.basename(path.dirname(dirPath)) || '/';
  const dateIso = new Date().toISOString().slice(0, 10);

  const targets = [
    {
      target: path.join(dirPath, 'ROOM.md'),
      content: roomMdTemplate({ section: section, parent: parent, dateIso: dateIso }),
    },
    {
      target: path.join(dirPath, 'MINTO.md'),
      content: mintoMdTemplate({ section: section, dateIso: dateIso }),
    },
  ];

  for (const t of targets) {
    try {
      if (fs.existsSync(t.target) && !force) {
        result.skipped.push(t.target);
        process.stdout.write('⬜ skipped: ' + t.target + ' (exists; pass --force to overwrite)\n');
        continue;
      }
      atomicWrite(t.target, t.content);
      result.wrote.push(t.target);
      process.stdout.write('✓ wrote: ' + t.target + '\n');
    } catch (err) {
      result.errors.push({ path: t.target, message: err.message });
      process.stderr.write('⚠ error: ' + t.target + ' -- ' + err.message + '\n');
    }
  }

  return result;
}

// ── Recursive walk ───────────────────────────────────────────────────

function walkRecursive(rootPath, options) {
  const aggregate = { wrote: [], skipped: [], errors: [] };
  const startDepth = 0;

  function visit(dirPath, depth) {
    if (depth > MAX_DEPTH) return;

    // Generate for this directory.
    const r = generateForDir(dirPath, options);
    aggregate.wrote.push.apply(aggregate.wrote, r.wrote);
    aggregate.skipped.push.apply(aggregate.skipped, r.skipped);
    aggregate.errors.push.apply(aggregate.errors, r.errors);

    // Walk children.
    let entries;
    try {
      entries = fs.readdirSync(dirPath, { withFileTypes: true });
    } catch (err) {
      aggregate.errors.push({ path: dirPath, message: err.message });
      return;
    }

    for (const ent of entries) {
      if (!ent.isDirectory()) continue;
      if (SKIP_DIRS.has(ent.name)) continue;
      // Defensive: skip any other dotted dir not explicitly in SKIP_DIRS.
      if (ent.name.startsWith('.')) continue;
      visit(path.join(dirPath, ent.name), depth + 1);
    }
  }

  visit(rootPath, startDepth);
  return aggregate;
}

// ── Main ─────────────────────────────────────────────────────────────

function main() {
  const argv = process.argv.slice(2);
  const parsed = parseArgs(argv);

  if (parsed.flags.help) {
    process.stdout.write(usageText() + '\n');
    process.exit(0);
  }

  if (parsed.unknown) {
    process.stderr.write('⚠ unknown flag: ' + parsed.unknown + '\n');
    process.stderr.write(usageText() + '\n');
    process.exit(2);
  }

  if (parsed.positional.length === 0) {
    process.stderr.write('⚠ Cannot generate: no directory specified\n');
    process.stderr.write('  Why: positional <dir> argument is required\n');
    process.stderr.write('  Fix: node scripts/generate-section-intelligence.cjs <dir> [--recursive]\n');
    process.exit(2);
  }

  const target = path.resolve(parsed.positional[0]);

  // SKILL.md §7 error pattern: the 3-line cross-mark/Why/Fix template is
  // reframed using ⚠ here since the cross-mark glyph is not in the approved
  // 12-glyph vocabulary.
  let stat;
  try {
    stat = fs.statSync(target);
  } catch (_err) {
    process.stderr.write('⚠ Cannot generate: directory not found\n');
    process.stderr.write('  Why: ' + target + ' does not exist\n');
    process.stderr.write('  Fix: mkdir -p ' + target + '\n');
    process.exit(1);
  }
  if (!stat.isDirectory()) {
    process.stderr.write('⚠ Cannot generate: target is not a directory\n');
    process.stderr.write('  Why: ' + target + ' exists but is not a directory\n');
    process.stderr.write('  Fix: pass a path to a directory, not a file\n');
    process.exit(1);
  }

  const result = parsed.flags.recursive
    ? walkRecursive(target, { force: parsed.flags.force })
    : generateForDir(target, { force: parsed.flags.force });

  // Summary line uses approved glyphs only.
  process.stdout.write(
    '\n✓ wrote ' + result.wrote.length + ' files / ' +
      '⬜ skipped ' + result.skipped.length + ' files'
  );
  if (result.errors.length > 0) {
    process.stdout.write(' / ⚠ ' + result.errors.length + ' errors');
  }
  process.stdout.write('\n');

  process.exit(result.errors.length > 0 ? 1 : 0);
}

main();
