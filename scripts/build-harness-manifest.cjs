// loadPolicies(rootDir) -- read + validate every policy file in the policy
// directory. Per-file try/catch (T-233-01 / T-217-01 self-DoS-avoidance
// pattern): one malformed file is reported by name and skipped from the
// returned `policies` list, and the loop NEVER aborts the rest of the scan.
// Returns { policies: [{fileName, id, policy}], findings: string[] }.
// ---------------------------------------------------------------------------
function loadPolicies(rootDir) {
  const dirAbs = rootDir || POLICIES_ABS;
  const schema = loadPolicySchema();
  const fileNames = listPolicyFileNames(dirAbs);
  const policies = [];
  const findings = [];

  for (const fileName of fileNames) {
    let parsed;
    try {
      parsed = JSON.parse(fs.readFileSync(path.join(dirAbs, fileName), 'utf8'));
    } catch (e) {
      findings.push(
        'MALFORMED: policy file ' + fileName + ' is not valid JSON (' + e.message + '). ' +
          'Recovery: fix the JSON syntax in data/harness-policies/' + fileName + '.'
      );
      continue;
    }
    const fileFindings = validatePolicyFile(parsed, fileName, schema);
    if (fileFindings.length) {
      for (const f of fileFindings) findings.push(f);
      continue;
    }
    policies.push({ fileName, id: parsed.id, policy: parsed });
  }

  return { policies, findings };
}

// ---------------------------------------------------------------------------
// runContractChecks(rootDir) -- Phase 298 Plan 13 (SEED-032, R-06). Runs every
// `kind: "contract"` policy in data/harness-policies/ INLINE (pure file
// reads, no spawn, no runner): each declared phrase must be a literal
// substring of its declared surface file, and the declared byte_budget's
// EVALUATED constant (required and read, never file-statted) must sit at or
// under its declared limit. The generator HARDCODES NO PHRASE of its own --
// `contract-parity-larry.json` is the single declaration (T-298-27); a grep
// for two of its pinned phrases inside this file must return zero. A missing
// phrase or a busted budget produces ONE named finding: the surface role,
// path and the exact missing phrase, or the constant name, the measured
// bytes and the limit -- so the failure is actionable without opening the
// policy file. Returns an array of finding strings (empty = clean).
// ---------------------------------------------------------------------------
function runContractChecks(rootDir) {
  const dirAbs = rootDir || REPO_ROOT;
  const { policies } = loadPolicies(POLICIES_ABS);
  const findings = [];
  const RECOVERY_CONTRACT =
    'Recovery: restore the declared phrase, or the declared byte budget, or ' +
    'update data/harness-policies/<id>.json if the contract itself changed, ' +
    'then re-run node scripts/build-harness-manifest.cjs --check.';

  for (const entry of policies) {
    const policy = entry && entry.policy;
    if (!policy || policy.kind !== 'contract') continue;
    const fileName = entry.fileName;

    const surfaces = Array.isArray(policy.surfaces) ? policy.surfaces : [];
    for (const surface of surfaces) {
      if (!surface || typeof surface.path !== 'string') continue;
      const absSurfacePath = path.join(dirAbs, surface.path);
      const buf = readBytes(absSurfacePath);
      const text = buf ? buf.toString('utf8') : null;
      const phrases = Array.isArray(surface.phrases) ? surface.phrases : [];
      for (const phrase of phrases) {
        if (typeof phrase !== 'string') continue;
        if (text === null || text.indexOf(phrase) === -1) {
          findings.push(
            'CONTRACT: ' + fileName + ' declares the phrase ' + JSON.stringify(phrase) +
              ' on surface "' + (surface.role || surface.path) + '" (' + surface.path +
              '), but it is not present on disk. ' + RECOVERY_CONTRACT
          );
        }
      }
    }

    const budget = policy.byte_budget;
    if (budget && typeof budget.path === 'string' && typeof budget.constant === 'string' &&
        typeof budget.limit === 'number') {
      const absModulePath = path.resolve(dirAbs, budget.path);
      let value;
      try {
        const resolved = require.resolve(absModulePath);
        delete require.cache[resolved];
        const mod = require(absModulePath);
        value = mod && mod[budget.constant];
      } catch (_e) {
        value = undefined;
      }
      if (typeof value !== 'string') {
        findings.push(
          'CONTRACT: ' + fileName + ' declares byte_budget constant "' + budget.constant +
            '" on ' + budget.path + ', but requiring the module and reading that export ' +
            'failed. ' + RECOVERY_CONTRACT
        );
      } else {
        const measured = Buffer.byteLength(value, 'utf8');
        if (measured > budget.limit) {
          findings.push(
            'CONTRACT: ' + fileName + ' byte_budget constant "' + budget.constant + '" (' +
              budget.path + ') measured ' + measured + ' bytes, exceeding its declared ' +
              'limit of ' + budget.limit + ' bytes. ' + RECOVERY_CONTRACT
          );
        }
      }
    }
  }

  return findings;
}

// ---------------------------------------------------------------------------
// buildManifest() -- the core. Emits the declared descriptor object:
//   { ontology_ref, generated_note, methodology_tier, version, maps }
// where maps is EXACTLY the three { role, path, digest, source_count } entries
// (posture / wiring / ranked_next_reach). NO per-surface rows. NO inlined map
// contents. methodology_tier=mindrian-operation machinery metadata (D-167-01).
// ---------------------------------------------------------------------------
function buildManifest() {
  const maps = MAP_BINDINGS.map((b) => buildMapEntry(b));
  const runtime_surfaces = RUNTIME_SURFACE_BINDINGS.map((b) => buildSurfaceEntry(b));
  const larry_surfaces = LARRY_SURFACE_BINDINGS.map((b) => buildSurfaceEntry(b));
  const policyCount = listPolicyFileNames(POLICIES_ABS).length;
  return {
    ontology_ref:
      'data/command-registry.json + data/connector-registry.json + ' +
      'data/brain-orchestration-projection.json',
    generated_note: GENERATED_NOTE,
    methodology_tier: TIER_OP,
    version: MANIFEST_VERSION,
    maps: maps,
    runtime_surfaces: runtime_surfaces,
    policies: {
      path: POLICIES_DIR,
      digest: digestDirectory(POLICIES_ABS),
      count: policyCount,
    },
    larry_surfaces: larry_surfaces,
    fixture_ref: {
      path: FIXTURE_DIR,
      digest: digestDirectory(FIXTURE_ABS),
    },
  };
}

// ---------------------------------------------------------------------------
// serializeManifest(manifest) -- deterministic JSON + a single trailing newline
// (byte-stable across machines), mirroring the shipped serialize* idiom. Emits
// ONLY the serialized fields in a stable key order; each maps entry emits its
// four keys in a stable order.
// ---------------------------------------------------------------------------
function serializeManifest(manifest) {
  const clean = {
    ontology_ref: manifest.ontology_ref,
    generated_note: manifest.generated_note,
    methodology_tier: manifest.methodology_tier,
    version: manifest.version,
    maps: (Array.isArray(manifest.maps) ? manifest.maps : []).map((m) => ({
      role: m.role,
      path: m.path,
      digest: m.digest,
      source_count: m.source_count,
    })),
    runtime_surfaces: (Array.isArray(manifest.runtime_surfaces)
      ? manifest.runtime_surfaces
      : []
    ).map((s) => ({
      role: s.role,
      path: s.path,
      digest: s.digest,
    })),
    policies: {
      path: manifest.policies && manifest.policies.path,
      digest: manifest.policies && manifest.policies.digest,
      count: manifest.policies && manifest.policies.count,
    },
    larry_surfaces: (Array.isArray(manifest.larry_surfaces)
      ? manifest.larry_surfaces
      : []
    ).map((s) => ({
      role: s.role,
      path: s.path,
      digest: s.digest,
    })),
    fixture_ref: {
      path: manifest.fixture_ref && manifest.fixture_ref.path,
      digest: manifest.fixture_ref && manifest.fixture_ref.digest,
    },
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// validateManifest(manifest) -- the 3-mode drift taxonomy (D-167-01 / D-167-03).
// Returns { stale, unresolved, malformed }: three categorized arrays of error
// strings (each empty = that mode is clean). PURE with respect to the Brain:
// reads ONLY the passed manifest + the committed on-disk manifest file (for the
// byte-compare) + the three named source paths (for the resolve check). ZERO
// Brain/network calls (Part 8). Mirrors validateProjection in
// build-orchestration-projection.cjs (categorized error arrays exercised
// directly by the test without spawning a subprocess).
//
//   STALE       -- the serialized regeneration differs byte-for-byte from the
//                  committed data/harness-manifest.json (a source map changed, or
//                  the committed file was hand-edited, without regenerating).
//   UNRESOLVED  -- a named map path does not exist on disk (a spoofed binding).
//   MALFORMED   -- a maps entry is missing a required key (role / path / digest),
//                  OR the maps section is not exactly the three declared roles
//                  (an extra entry, a per-surface row, or a missing role).
// ---------------------------------------------------------------------------
function validateManifest(manifest) {
  const stale = [];
  const unresolved = [];
  const malformed = [];

  const RECOVERY = 'Run: node scripts/build-harness-manifest.cjs';

  const m = manifest && typeof manifest === 'object' ? manifest : {};
  const maps = Array.isArray(m.maps) ? m.maps : [];

  // ---- STALE: byte-compare the serialized manifest vs the committed file. ----
  const serialized = serializeManifest(m);
  const onDisk = fs.existsSync(MANIFEST_PATH)
    ? fs.readFileSync(MANIFEST_PATH, 'utf8')
    : '';
  if (onDisk !== serialized) {
    stale.push(
      'STALE: data/harness-manifest.json diverges from the regenerated ' +
        'manifest (a source map changed without regenerating, or the committed ' +
        'file was hand-edited). ' + RECOVERY
    );
  }

  // ---- UNRESOLVED: each of the three named map paths must exist on disk. ----
  for (const binding of MAP_BINDINGS) {
    if (!fs.existsSync(binding.absPath)) {
      unresolved.push(
        'UNRESOLVED: the ' + binding.role + ' map path "' + binding.relPath +
          '" does not exist on disk (a fabricated / missing map binding). ' +
          RECOVERY
      );
    }
  }

  // ---- MALFORMED: per-entry well-formedness + EXACTLY the three roles. ----
  // The maps section must carry EXACTLY three entries, one per declared role,
  // and NO per-surface row (HIGH-1: a 3-map digest, never a per-surface
  // registry). An extra entry, a missing role, or a non-declared role key is a
  // MALFORMED finding.
  const declaredRoles = MAP_BINDINGS.map((b) => b.role);
  if (maps.length !== declaredRoles.length) {
    malformed.push(
      'MALFORMED: the maps section has ' + maps.length + ' entries; expected ' +
        'EXACTLY ' + declaredRoles.length + ' (one per map: ' +
        declaredRoles.join(', ') + '). A per-surface row or an extra entry ' +
        'breaks the 3-map digest invariant (D-166-03 / HIGH-1). ' + RECOVERY
    );
  }
  const seenRoles = new Set();
  for (const entry of maps) {
    if (!entry || typeof entry !== 'object') {
      malformed.push('MALFORMED: a maps entry is not an object. ' + RECOVERY);
      continue;
    }
    const missing = [];
    if (typeof entry.role !== 'string' || !entry.role) missing.push('role');
    if (typeof entry.path !== 'string' || !entry.path) missing.push('path');
    if (typeof entry.digest !== 'string' || !entry.digest) missing.push('digest');
    if (missing.length) {
      malformed.push(
        'MALFORMED: maps entry ' + JSON.stringify(entry.role || entry.path || '?') +
          ' is missing required key(s): ' + missing.join(', ') + '. ' + RECOVERY
      );
    }
    if (typeof entry.role === 'string') {
      if (!declaredRoles.includes(entry.role)) {
        malformed.push(
          'MALFORMED: maps entry carries non-declared role "' + entry.role +
            '" (a per-surface row or an invented role; the only legal roles are ' +
            declaredRoles.join(', ') + '). ' + RECOVERY
        );
      }
      if (seenRoles.has(entry.role)) {
        malformed.push(
          'MALFORMED: duplicate maps role "' + entry.role + '". ' + RECOVERY
        );
      }
      seenRoles.add(entry.role);
    }
  }

  // ---- RUNTIME-SURFACE DRIFT (Phase 201-01, D-201-1, fail closed). Each
  // declared runtime surface's committed digest must equal the sha256 of the
  // on-disk code file. A missing surface file is UNRESOLVED; a digest that
  // diverges from the file is STALE and NAMES THE ROLE, so --check fails closed
  // the moment the declared harness and the running harness diverge. This reads
  // the COMMITTED manifest (the byte-compare STALE above already covers a
  // hand-edited / stale committed file); here we prove the declared surface
  // fingerprints still match the code they fingerprint. Zero Brain/network. ----
  let committed = null;
  try {
    committed = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  } catch (_e) {
    committed = null;
  }
  const committedSurfaces =
    committed && Array.isArray(committed.runtime_surfaces)
      ? committed.runtime_surfaces
      : [];
  for (const binding of RUNTIME_SURFACE_BINDINGS) {
    if (!fs.existsSync(binding.absPath)) {
      unresolved.push(
        'UNRESOLVED: the ' + binding.role + ' runtime surface "' +
          binding.relPath + '" does not exist on disk (a fabricated / missing ' +
          'surface binding). ' + RECOVERY
      );
      continue;
    }
    const declared = committedSurfaces.find(
      (s) => s && s.role === binding.role
    );
    // A committed manifest that never declared this surface is caught by the
    // byte-compare STALE (the regeneration adds the missing entry); skip here.
    if (!declared || typeof declared.digest !== 'string') continue;
    const actual = digestBytes(fs.readFileSync(binding.absPath));
    if (declared.digest !== actual) {
      stale.push(
        'STALE: the ' + binding.role + ' runtime surface (' + binding.relPath +
          ') digest in the manifest drifts from the on-disk file - the DECLARED ' +
          'harness and the RUNNING harness have diverged. ' + RECOVERY
      );
    }
  }

  // ---- LARRY-SURFACE DRIFT (Phase 298, SEED-032). Copies the runtime-surface
  // drift loop above EXACTLY, over LARRY_SURFACE_BINDINGS / committed.larry_surfaces
  // instead. ----
  const committedLarrySurfaces =
    committed && Array.isArray(committed.larry_surfaces) ? committed.larry_surfaces : [];
  for (const binding of LARRY_SURFACE_BINDINGS) {
    if (!fs.existsSync(binding.absPath)) {
      unresolved.push(
        'UNRESOLVED: the ' + binding.role + ' larry surface "' +
          binding.relPath + '" does not exist on disk (a fabricated / missing ' +
          'surface binding). ' + RECOVERY
      );
      continue;
    }
    const declaredLarry = committedLarrySurfaces.find(
      (s) => s && s.role === binding.role
    );
    if (!declaredLarry || typeof declaredLarry.digest !== 'string') continue;
    const actualLarry = digestBytes(fs.readFileSync(binding.absPath));
    if (declaredLarry.digest !== actualLarry) {
      stale.push(
        'STALE: the ' + binding.role + ' larry surface (' + binding.relPath +
          ') digest in the manifest drifts from the on-disk file - the DECLARED ' +
          'harness and the RUNNING harness have diverged. ' + RECOVERY
      );
    }
  }

  // ---- POLICIES DIRECTORY DRIFT (Phase 298). A directory-digest divergence
  // between the committed manifest's `policies.digest` and the live directory. ----
  if (!fs.existsSync(POLICIES_ABS)) {
    unresolved.push(
      'UNRESOLVED: the policies directory "' + POLICIES_DIR +
        '" does not exist on disk (a fabricated / missing policies binding). ' + RECOVERY
    );
  } else if (committed && committed.policies && typeof committed.policies.digest === 'string') {
    const actualPolicies = digestDirectory(POLICIES_ABS);
    if (committed.policies.digest !== actualPolicies) {
      stale.push(
        'STALE: the policies directory (' + POLICIES_DIR + ') digest in the manifest ' +
          'drifts from the on-disk directory - a policy file changed without regenerating. ' +
          RECOVERY
      );
    }
  }

  // ---- FIXTURE_REF DRIFT (Phase 298). A directory-digest divergence between
  // the committed manifest's `fixture_ref.digest` and the live directory. ----
  if (!fs.existsSync(FIXTURE_ABS)) {
    unresolved.push(
      'UNRESOLVED: the fixture directory "' + FIXTURE_DIR +
        '" does not exist on disk (a fabricated / missing fixture_ref binding). ' + RECOVERY
    );
  } else if (committed && committed.fixture_ref && typeof committed.fixture_ref.digest === 'string') {
    const actualFixture = digestDirectory(FIXTURE_ABS);
    if (committed.fixture_ref.digest !== actualFixture) {
      stale.push(
        'STALE: the fixture_ref directory (' + FIXTURE_DIR + ') digest in the manifest ' +
          'drifts from the on-disk directory - the converged-room fixture changed without ' +
          'regenerating. ' + RECOVERY
      );
    }
  }

  return { stale, unresolved, malformed };
}

// ---------------------------------------------------------------------------
// runCheck() -- the --check mode. Regenerate the manifest from the LIVE sources
// in memory, run validateManifest, print each named finding + its recovery line
// to stderr, and exit non-zero on ANY finding. Exit 0 + an OK line on a clean
// repo. Mirrors build-orchestration-projection.cjs runCheck. ZERO Brain/network
// calls (Part 8).
// ---------------------------------------------------------------------------
function runCheck() {
  const manifest = buildManifest();
  const { stale, unresolved, malformed } = validateManifest(manifest);
  // Phase 298 (SEED-032): validate every policy file against the closed
  // schema. An invalid policy file is a MALFORMED finding naming the file and
  // the failing key; one bad file is reported and skipped, never aborting the
  // rest of the scan (T-233-01 / T-217-01 self-DoS-avoidance pattern).
  const { findings: policyFindings } = loadPolicies(POLICIES_ABS);
  // Phase 298 Plan 13 (R-06): the contract-* policies, run inline as a fourth
  // finding class beside stale/unresolved/malformed -- a dropped Larry phrase
  // or a busted Desktop-wire byte budget fails --check by name.
  const contractFindings = runContractChecks(REPO_ROOT);
  const all = [...stale, ...unresolved, ...malformed, ...policyFindings, ...contractFindings];
  if (all.length) {
    console.error(all.join('\n'));
    console.error(
      'Recovery: regenerate the manifest, then re-stage it: ' +
        'node scripts/build-harness-manifest.cjs'
    );
    process.exit(1);
    return;
  }
  console.log('harness-manifest: OK');
}

// ---------------------------------------------------------------------------
// writeManifest() -- the default + --refresh write path: re-derive the digests
// from the live sources and write the artifact (idempotent). --refresh is the
// manifest's analogue of the connector --refresh-names: it re-reads the sources,
// re-digests, and re-writes, which is a byte-identical no-op when nothing
// changed.
// ---------------------------------------------------------------------------
function writeManifest() {
  const manifest = buildManifest();
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(MANIFEST_PATH, serializeManifest(manifest));
  console.log(
    'Wrote data/harness-manifest.json (' + manifest.maps.length + ' map entries: ' +
      manifest.maps.map((e) => e.role).join(', ') + '; ' +
      manifest.runtime_surfaces.length + ' runtime surfaces: ' +
      manifest.runtime_surfaces.map((e) => e.role).join(', ') + '; ' +
      manifest.policies.count + ' policies digested; ' +
      manifest.larry_surfaces.length + ' larry surfaces: ' +
      manifest.larry_surfaces.map((e) => e.role).join(', ') + ')'
  );
}

// ---------------------------------------------------------------------------
// main() -- the 3-branch entry: default write / --check / --refresh.
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--check')) {
    runCheck();
    return;
  }

  // --refresh re-derives the digests + re-writes (idempotent). The default
  // branch is the same write path; --refresh is named for parity with the
  // connector generator's --refresh-names idiom.
  writeManifest();
}

