// ---------------------------------------------------------------------------
// readBytes(p) -- read a committed source file's raw bytes. Returns null on any
// failure so the generator/validator degrades rather than throwing (mirrors the
// shipped generators' readJson degrade discipline).
// ---------------------------------------------------------------------------
function readBytes(p) {
  try {
    return fs.readFileSync(p);
  } catch (_e) {
    return null;
  }
}

// ---------------------------------------------------------------------------
// digestBytes(buf) -- sha256 hex of the raw on-disk bytes. This is MACHINERY
// METADATA (a fixed-length hex fingerprint), NEVER the map's contents. A digest
// changes iff the map's bytes change, so a single surface landing in
// connector-registry.json flips the wiring entry's digest transitively.
// ---------------------------------------------------------------------------
function digestBytes(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

// ---------------------------------------------------------------------------
// primaryArrayCount(buf, key) -- parse the JSON bytes and return the length of
// the named primary array (a scalar count, NOT the contents). Returns 0 on a
// missing / malformed source or a non-array key, so the count degrades to a
// legible zero rather than throwing.
// ---------------------------------------------------------------------------
function primaryArrayCount(buf, key) {
  if (!buf) return 0;
  let parsed;
  try {
    parsed = JSON.parse(buf.toString('utf8'));
  } catch (_e) {
    return 0;
  }
  const arr = parsed && parsed[key];
  return Array.isArray(arr) ? arr.length : 0;
}

// ---------------------------------------------------------------------------
// buildMapEntry(binding) -- build ONE { role, path, digest, source_count } map
// entry. Reads the on-disk bytes once: digests them and counts the primary
// array. A missing source yields a stable empty-digest sentinel (the sha256 of
// the empty byte string) + a zero count, so the manifest is still byte-stable
// when a source is absent; --check then flags the absence as UNRESOLVED.
// ---------------------------------------------------------------------------
function buildMapEntry(binding) {
  const buf = readBytes(binding.absPath);
  const digest = buf ? digestBytes(buf) : digestBytes(Buffer.from(''));
  const source_count = primaryArrayCount(buf, binding.primaryArrayKey);
  return {
    role: binding.role,
    path: binding.relPath,
    digest: digest,
    source_count: source_count,
  };
}

// ---------------------------------------------------------------------------
// buildSurfaceEntry(binding) -- build ONE { role, path, digest } runtime-surface
// entry (Phase 201-01, D-201-1 digest-only). Reads the on-disk code bytes once and
// sha256-digests them (machinery metadata, NOT contents). A missing surface yields
// the stable empty-digest sentinel so the manifest stays byte-stable when a file is
// absent; --check then flags the absence as UNRESOLVED. There is NO source_count:
// a runtime surface is one code file, not an array of sources.
// ---------------------------------------------------------------------------
function buildSurfaceEntry(binding) {
  const buf = readBytes(binding.absPath);
  const digest = buf ? digestBytes(buf) : digestBytes(Buffer.from(''));
  return {
    role: binding.role,
    path: binding.relPath,
    digest: digest,
  };
}

// ---------------------------------------------------------------------------
// listFilesRecursive(rootDir) -- list every FILE under rootDir (recursing into
// subdirectories), as paths relative to rootDir using '/' separators
// regardless of OS, in a plain lexicographic sort over the FULL relative path.
// Returns [] for a missing or unreadable directory (degrade, never throw).
// ---------------------------------------------------------------------------
function listFilesRecursive(rootDir) {
  const out = [];
  function walk(dirAbs, relPrefix) {
    let entries;
    try {
      entries = fs.readdirSync(dirAbs, { withFileTypes: true });
    } catch (_e) {
      return;
    }
    for (const entry of entries) {
      const relPath = relPrefix ? relPrefix + '/' + entry.name : entry.name;
      const absPath = path.join(dirAbs, entry.name);
      if (entry.isDirectory()) {
        walk(absPath, relPath);
      } else if (entry.isFile()) {
        out.push(relPath);
      }
    }
  }
  walk(rootDir, '');
  return out.sort();
}

// ---------------------------------------------------------------------------
// digestDirectory(dirPath) -- digest a DIRECTORY as ONE value (Phase 298,
// SEED-032). There is NO shipped directory-digest precedent in this file (the
// three existing digests are all single-file digestBytes calls), so THE
// COMPOSITION RULE IS STATED HERE, the way every other invariant in this file
// is stated:
//
//   1. List every file under dirPath, recursing into subdirectories.
//   2. Sort the relative paths with a plain lexicographic sort (the full
//      relative path, '/' separators, no OS-specific ordering).
//   3. For each file, in that sorted order, build the line:
//        <relative-path> + NUL(\0) + <lowercase-hex-sha256-of-the-file-bytes> + \n
//   4. Concatenate those lines in order and return the sha256 hex of the
//      concatenation.
//
// This makes the digest filesystem-independent (relative paths only) and
// RENAME-SENSITIVE: renaming a file with byte-identical content changes the
// digest, because the relative path is part of what is hashed - which is the
// correct behavior for a declared harness fingerprint. A missing directory (or
// an empty one) yields the sha256 of the empty buffer, the SAME stable
// sentinel readBytes's degrade path already uses for a missing single file.
// ---------------------------------------------------------------------------
function digestDirectory(dirPath) {
  const files = listFilesRecursive(dirPath);
  if (files.length === 0) {
    return digestBytes(Buffer.from(''));
  }
  const lines = files.map((relPath) => {
    const buf = readBytes(path.join(dirPath, relPath));
    const fileDigest = buf ? digestBytes(buf) : digestBytes(Buffer.from(''));
    return relPath + '\0' + fileDigest + '\n';
  });
  return digestBytes(Buffer.from(lines.join(''), 'utf8'));
}

