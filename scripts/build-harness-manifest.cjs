#!/usr/bin/env node
'use strict';

/*
 * Phase 167-01 Task 1 - the declared harness MANIFEST generator (HARN-01,
 * D-167-01, D-167-06).
 *
 * Produces data/harness-manifest.json: the DECLARED, VERSIONED descriptor that
 * NAMES the three existing recipe maps as ONE binding and nothing more. It is a
 * READ LAYER OVER the three maps (a 3-MAP DIGEST), not a merge and not a
 * per-surface registry. It does NOT merge or retire them (D-166-03 PRESERVED).
 *
 * THE GENERATOR IS A PART 7 REUSE SIBLING of
 * scripts/build-orchestration-projection.cjs and
 * scripts/build-connector-registry.cjs. It mirrors the shipped generator idiom
 * wholesale: a deterministic source read -> build -> serialize
 * (JSON.stringify(...,2) + a single trailing newline, byte-stable across
 * machines) -> a 3-branch main (default write / --check / --refresh). The ONE
 * structural difference is grain: the connector/projection generators emit a
 * per-surface / per-node registry; this manifest emits EXACTLY THREE map entries
 * (posture / wiring / ranked_next_reach) and NEVER a per-surface row. A surface
 * (a /mos command, an agent, a skill) is reflected ONLY TRANSITIVELY: it lands
 * in connector-registry.json (its real home, the per-surface registry), the
 * wiring map's digest + source_count change, and this manifest's wiring entry
 * digest + source_count update to match. The manifest digests the three maps; it
 * never inlines or enumerates the surfaces inside them. This is what keeps
 * D-166-03 inviolate.
 *
 * HIGH-1 (LOCKED): the manifest is a 3-MAP DIGEST naming EXACTLY the three maps
 * as { role, path, digest(sha256), source_count }:
 *   posture            -> data/command-registry.json
 *   wiring             -> data/connector-registry.json
 *   ranked_next_reach  -> data/brain-orchestration-projection.json
 *
 * Canon Part 8 (The Graph Boundary) + the Phase 157 amendment (Appendix D entry
 * 19): the manifest carries methodology_tier=mindrian-operation machinery
 * metadata ONLY (the sha256 digests are machinery metadata, NOT contents). It
 * NEVER carries user content. It is a LOCAL artifact: there is NO live Brain read
 * and NO live Brain write anywhere in this file - no brain-client require, no
 * fetch, no http. It is NOT folded into the Brain projection (D-167-01). NO new
 * deps; node built-ins only (node:fs, node:path, node:crypto for sha256). NO
 * YAML; NO TS.
 *
 * Usage:
 *   node scripts/build-harness-manifest.cjs
 *       read the three maps -> write data/harness-manifest.json
 *   node scripts/build-harness-manifest.cjs --check
 *       regenerate in memory, assert STALE / UNRESOLVED / MALFORMED, exit-1 on
 *       any finding with a stderr recovery line, else print an OK line
 *   node scripts/build-harness-manifest.cjs --refresh
 *       re-derive the digests + re-write the artifact (idempotent)
 *
 * House rule: hyphens only, no em-dashes.
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const REPO_ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(REPO_ROOT, 'data');

const COMMAND_REGISTRY_PATH = path.join(DATA_DIR, 'command-registry.json');
const CONNECTOR_REGISTRY_PATH = path.join(DATA_DIR, 'connector-registry.json');
const PROJECTION_PATH = path.join(DATA_DIR, 'brain-orchestration-projection.json');
const MANIFEST_PATH = path.join(DATA_DIR, 'harness-manifest.json');

const GENERATED_NOTE =
  'GENERATED by scripts/build-harness-manifest.cjs - do not edit by hand';

// The only legal methodology_tier for this LOCAL machinery descriptor (Canon
// Part 8, Phase 157 amendment). The manifest is mindrian-operation machinery
// metadata, never pws teaching IP and never user content.
const TIER_OP = 'mindrian-operation';

const MANIFEST_VERSION = 1;

// ---------------------------------------------------------------------------
// THE THREE-MAP BINDING (HIGH-1, D-167-01). EXACTLY three entries, one per map.
// Each entry declares { role, relPath, primaryArrayKey }. The generator reads
// the on-disk bytes of each path, sha256-digests them (machinery metadata, NOT
// contents), and counts the primary array's length for source_count. There is
// NO fourth entry, and NO per-surface row: a surface is digested transitively
// inside the wiring map's source_count.
//
// role -> map (LOCKED naming):
//   posture            command-registry.json (the posture / autonomy authority)
//   wiring             connector-registry.json (the reach -> surface wiring)
//   ranked_next_reach  brain-orchestration-projection.json (the ranked next-reach)
// ---------------------------------------------------------------------------
const MAP_BINDINGS = Object.freeze([
  Object.freeze({
    role: 'posture',
    relPath: 'data/command-registry.json',
    absPath: COMMAND_REGISTRY_PATH,
    primaryArrayKey: 'commands',
  }),
  Object.freeze({
    role: 'wiring',
    relPath: 'data/connector-registry.json',
    absPath: CONNECTOR_REGISTRY_PATH,
    primaryArrayKey: 'connectors',
  }),
  Object.freeze({
    role: 'ranked_next_reach',
    relPath: 'data/brain-orchestration-projection.json',
    absPath: PROJECTION_PATH,
    primaryArrayKey: 'nodes',
  }),
]);

// ---------------------------------------------------------------------------
// THE RUNTIME-SURFACE BINDINGS (Phase 201-01, SEED-032, D-201-1). The agent is
// Model + Harness; the three maps above declare the harness's DATA, but SEED-032's
// point is that the harness's RUNTIME surfaces - the code the harness runs ON -
// belong in the SAME declared manifest too. These four bindings name each runtime
// surface as { role, path, digest(sha256) } - DIGEST-ONLY (D-201-1, the RECOMMENDED
// depth): a fixed-length fingerprint of the on-disk bytes, machinery metadata,
// NEVER the file contents. There is NO source_count (these are code files, not
// arrays of sources) and NO richer per-surface schema - a richer schema would turn
// the read/descriptor into a second orchestration brain (Canon Part 11: one
// governed path). This block is purely ADDITIVE: it DECLARES what already runs
// (Part 7), retires no map (D-166-03), keeps maps at EXACTLY three, and opens no
// Brain wire (Part 8). --check re-digests these files and fails closed on any drift
// between the declared harness and the on-disk harness.
//
// role -> the runtime surface (the code file that IS that surface):
//   orchestration_spine  lib/core/chain-executor.cjs         (the runChain spine)
//   decide_engine        lib/core/navigation-engine.cjs      (the decide() engine)
//   cockpit              lib/statusline/cockpit-renderer.cjs (the statusline cockpit)
//   brain_orchestration  lib/core/directive-envelope.cjs     (the brain-orchestration reader)
// ---------------------------------------------------------------------------
const RUNTIME_SURFACE_BINDINGS = Object.freeze([
  Object.freeze({
    role: 'orchestration_spine',
    relPath: 'lib/core/chain-executor.cjs',
    absPath: path.join(REPO_ROOT, 'lib/core/chain-executor.cjs'),
  }),
  Object.freeze({
    role: 'decide_engine',
    relPath: 'lib/core/navigation-engine.cjs',
    absPath: path.join(REPO_ROOT, 'lib/core/navigation-engine.cjs'),
  }),
  Object.freeze({
    role: 'cockpit',
    relPath: 'lib/statusline/cockpit-renderer.cjs',
    absPath: path.join(REPO_ROOT, 'lib/statusline/cockpit-renderer.cjs'),
  }),
  Object.freeze({
    role: 'brain_orchestration',
    relPath: 'lib/core/directive-envelope.cjs',
    absPath: path.join(REPO_ROOT, 'lib/core/directive-envelope.cjs'),
  }),
]);

// ---------------------------------------------------------------------------
// The Part 8 boundary-scan field allowlists (D-167-06, BOG-10 sibling). SINGLE
// SOURCE OF TRUTH the Wave-1 boundary scan
// (tests/test-harness-manifest-part8-boundary.cjs) asserts against. A top-level
// manifest key outside NODE_FIELD_ALLOWLIST, or a maps-entry key outside
// ENTRY_FIELD_ALLOWLIST, is a Part 8 breach (a candidate user-content field) and
// fails the build before the artifact lands. Every name here is a GENERIC
// machinery field: an ontology reference, a generated note, a tier enum, a
// version int, the maps binding, and the per-entry { role, path, digest,
// source_count } machinery quadruple. NONE is a user-content channel.
const NODE_FIELD_ALLOWLIST = Object.freeze([
  'ontology_ref',
  'generated_note',
  'methodology_tier',
  'version',
  'maps',
  // Phase 201-01: the additive runtime-surface digest block. Each entry is the
  // generic { role, path, digest } machinery triple (a subset of
  // ENTRY_FIELD_ALLOWLIST); no source_count, no user-content channel.
  'runtime_surfaces',
]);

// Every maps entry is EXACTLY { role, path, digest, source_count }. A maps-entry
// key outside this set is a Part 8 breach.
const ENTRY_FIELD_ALLOWLIST = Object.freeze([
  'role',
  'path',
  'digest',
  'source_count',
]);

// ---------------------------------------------------------------------------
// readBytes(p) -- read a committed source file's raw bytes. Returns null on any
// failure so the generator/validator degrades rather than throwing (mirrors the
// shipped generators' readJson degrade discipline).
// ---------------------------------------------------------------------------
function readBytes(p) {
  try {
    return fs.readFileSync(p);
  } catch (_e) {
    return null;
  }
}

// ---------------------------------------------------------------------------
// digestBytes(buf) -- sha256 hex of the raw on-disk bytes. This is MACHINERY
// METADATA (a fixed-length hex fingerprint), NEVER the map's contents. A digest
// changes iff the map's bytes change, so a single surface landing in
// connector-registry.json flips the wiring entry's digest transitively.
// ---------------------------------------------------------------------------
function digestBytes(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

// ---------------------------------------------------------------------------
// primaryArrayCount(buf, key) -- parse the JSON bytes and return the length of
// the named primary array (a scalar count, NOT the contents). Returns 0 on a
// missing / malformed source or a non-array key, so the count degrades to a
// legible zero rather than throwing.
// ---------------------------------------------------------------------------
function primaryArrayCount(buf, key) {
  if (!buf) return 0;
  let parsed;
  try {
    parsed = JSON.parse(buf.toString('utf8'));
  } catch (_e) {
    return 0;
  }
  const arr = parsed && parsed[key];
  return Array.isArray(arr) ? arr.length : 0;
}

// ---------------------------------------------------------------------------
// buildMapEntry(binding) -- build ONE { role, path, digest, source_count } map
// entry. Reads the on-disk bytes once: digests them and counts the primary
// array. A missing source yields a stable empty-digest sentinel (the sha256 of
// the empty byte string) + a zero count, so the manifest is still byte-stable
// when a source is absent; --check then flags the absence as UNRESOLVED.
// ---------------------------------------------------------------------------
function buildMapEntry(binding) {
  const buf = readBytes(binding.absPath);
  const digest = buf ? digestBytes(buf) : digestBytes(Buffer.from(''));
  const source_count = primaryArrayCount(buf, binding.primaryArrayKey);
  return {
    role: binding.role,
    path: binding.relPath,
    digest: digest,
    source_count: source_count,
  };
}

// ---------------------------------------------------------------------------
// buildSurfaceEntry(binding) -- build ONE { role, path, digest } runtime-surface
// entry (Phase 201-01, D-201-1 digest-only). Reads the on-disk code bytes once and
// sha256-digests them (machinery metadata, NOT contents). A missing surface yields
// the stable empty-digest sentinel so the manifest stays byte-stable when a file is
// absent; --check then flags the absence as UNRESOLVED. There is NO source_count:
// a runtime surface is one code file, not an array of sources.
// ---------------------------------------------------------------------------
function buildSurfaceEntry(binding) {
  const buf = readBytes(binding.absPath);
  const digest = buf ? digestBytes(buf) : digestBytes(Buffer.from(''));
  return {
    role: binding.role,
    path: binding.relPath,
    digest: digest,
  };
}

// ---------------------------------------------------------------------------
// buildManifest() -- the core. Emits the declared descriptor object:
//   { ontology_ref, generated_note, methodology_tier, version, maps }
// where maps is EXACTLY the three { role, path, digest, source_count } entries
// (posture / wiring / ranked_next_reach). NO per-surface rows. NO inlined map
// contents. methodology_tier=mindrian-operation machinery metadata (D-167-01).
// ---------------------------------------------------------------------------
function buildManifest() {
  const maps = MAP_BINDINGS.map((b) => buildMapEntry(b));
  const runtime_surfaces = RUNTIME_SURFACE_BINDINGS.map((b) => buildSurfaceEntry(b));
  return {
    ontology_ref:
      'data/command-registry.json + data/connector-registry.json + ' +
      'data/brain-orchestration-projection.json',
    generated_note: GENERATED_NOTE,
    methodology_tier: TIER_OP,
    version: MANIFEST_VERSION,
    maps: maps,
    runtime_surfaces: runtime_surfaces,
  };
}

// ---------------------------------------------------------------------------
// serializeManifest(manifest) -- deterministic JSON + a single trailing newline
// (byte-stable across machines), mirroring the shipped serialize* idiom. Emits
// ONLY the serialized fields in a stable key order; each maps entry emits its
// four keys in a stable order.
// ---------------------------------------------------------------------------
function serializeManifest(manifest) {
  const clean = {
    ontology_ref: manifest.ontology_ref,
    generated_note: manifest.generated_note,
    methodology_tier: manifest.methodology_tier,
    version: manifest.version,
    maps: (Array.isArray(manifest.maps) ? manifest.maps : []).map((m) => ({
      role: m.role,
      path: m.path,
      digest: m.digest,
      source_count: m.source_count,
    })),
    runtime_surfaces: (Array.isArray(manifest.runtime_surfaces)
      ? manifest.runtime_surfaces
      : []
    ).map((s) => ({
      role: s.role,
      path: s.path,
      digest: s.digest,
    })),
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// validateManifest(manifest) -- the 3-mode drift taxonomy (D-167-01 / D-167-03).
// Returns { stale, unresolved, malformed }: three categorized arrays of error
// strings (each empty = that mode is clean). PURE with respect to the Brain:
// reads ONLY the passed manifest + the committed on-disk manifest file (for the
// byte-compare) + the three named source paths (for the resolve check). ZERO
// Brain/network calls (Part 8). Mirrors validateProjection in
// build-orchestration-projection.cjs (categorized error arrays exercised
// directly by the test without spawning a subprocess).
//
//   STALE       -- the serialized regeneration differs byte-for-byte from the
//                  committed data/harness-manifest.json (a source map changed, or
//                  the committed file was hand-edited, without regenerating).
//   UNRESOLVED  -- a named map path does not exist on disk (a spoofed binding).
//   MALFORMED   -- a maps entry is missing a required key (role / path / digest),
//                  OR the maps section is not exactly the three declared roles
//                  (an extra entry, a per-surface row, or a missing role).
// ---------------------------------------------------------------------------
function validateManifest(manifest) {
  const stale = [];
  const unresolved = [];
  const malformed = [];

  const RECOVERY = 'Run: node scripts/build-harness-manifest.cjs';

  const m = manifest && typeof manifest === 'object' ? manifest : {};
  const maps = Array.isArray(m.maps) ? m.maps : [];

  // ---- STALE: byte-compare the serialized manifest vs the committed file. ----
  const serialized = serializeManifest(m);
  const onDisk = fs.existsSync(MANIFEST_PATH)
    ? fs.readFileSync(MANIFEST_PATH, 'utf8')
    : '';
  if (onDisk !== serialized) {
    stale.push(
      'STALE: data/harness-manifest.json diverges from the regenerated ' +
        'manifest (a source map changed without regenerating, or the committed ' +
        'file was hand-edited). ' + RECOVERY
    );
  }

  // ---- UNRESOLVED: each of the three named map paths must exist on disk. ----
  for (const binding of MAP_BINDINGS) {
    if (!fs.existsSync(binding.absPath)) {
      unresolved.push(
        'UNRESOLVED: the ' + binding.role + ' map path "' + binding.relPath +
          '" does not exist on disk (a fabricated / missing map binding). ' +
          RECOVERY
      );
    }
  }

  // ---- MALFORMED: per-entry well-formedness + EXACTLY the three roles. ----
  // The maps section must carry EXACTLY three entries, one per declared role,
  // and NO per-surface row (HIGH-1: a 3-map digest, never a per-surface
  // registry). An extra entry, a missing role, or a non-declared role key is a
  // MALFORMED finding.
  const declaredRoles = MAP_BINDINGS.map((b) => b.role);
  if (maps.length !== declaredRoles.length) {
    malformed.push(
      'MALFORMED: the maps section has ' + maps.length + ' entries; expected ' +
        'EXACTLY ' + declaredRoles.length + ' (one per map: ' +
        declaredRoles.join(', ') + '). A per-surface row or an extra entry ' +
        'breaks the 3-map digest invariant (D-166-03 / HIGH-1). ' + RECOVERY
    );
  }
  const seenRoles = new Set();
  for (const entry of maps) {
    if (!entry || typeof entry !== 'object') {
      malformed.push('MALFORMED: a maps entry is not an object. ' + RECOVERY);
      continue;
    }
    const missing = [];
    if (typeof entry.role !== 'string' || !entry.role) missing.push('role');
    if (typeof entry.path !== 'string' || !entry.path) missing.push('path');
    if (typeof entry.digest !== 'string' || !entry.digest) missing.push('digest');
    if (missing.length) {
      malformed.push(
        'MALFORMED: maps entry ' + JSON.stringify(entry.role || entry.path || '?') +
          ' is missing required key(s): ' + missing.join(', ') + '. ' + RECOVERY
      );
    }
    if (typeof entry.role === 'string') {
      if (!declaredRoles.includes(entry.role)) {
        malformed.push(
          'MALFORMED: maps entry carries non-declared role "' + entry.role +
            '" (a per-surface row or an invented role; the only legal roles are ' +
            declaredRoles.join(', ') + '). ' + RECOVERY
        );
      }
      if (seenRoles.has(entry.role)) {
        malformed.push(
          'MALFORMED: duplicate maps role "' + entry.role + '". ' + RECOVERY
        );
      }
      seenRoles.add(entry.role);
    }
  }

  // ---- RUNTIME-SURFACE DRIFT (Phase 201-01, D-201-1, fail closed). Each
  // declared runtime surface's committed digest must equal the sha256 of the
  // on-disk code file. A missing surface file is UNRESOLVED; a digest that
  // diverges from the file is STALE and NAMES THE ROLE, so --check fails closed
  // the moment the declared harness and the running harness diverge. This reads
  // the COMMITTED manifest (the byte-compare STALE above already covers a
  // hand-edited / stale committed file); here we prove the declared surface
  // fingerprints still match the code they fingerprint. Zero Brain/network. ----
  let committed = null;
  try {
    committed = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
  } catch (_e) {
    committed = null;
  }
  const committedSurfaces =
    committed && Array.isArray(committed.runtime_surfaces)
      ? committed.runtime_surfaces
      : [];
  for (const binding of RUNTIME_SURFACE_BINDINGS) {
    if (!fs.existsSync(binding.absPath)) {
      unresolved.push(
        'UNRESOLVED: the ' + binding.role + ' runtime surface "' +
          binding.relPath + '" does not exist on disk (a fabricated / missing ' +
          'surface binding). ' + RECOVERY
      );
      continue;
    }
    const declared = committedSurfaces.find(
      (s) => s && s.role === binding.role
    );
    // A committed manifest that never declared this surface is caught by the
    // byte-compare STALE (the regeneration adds the missing entry); skip here.
    if (!declared || typeof declared.digest !== 'string') continue;
    const actual = digestBytes(fs.readFileSync(binding.absPath));
    if (declared.digest !== actual) {
      stale.push(
        'STALE: the ' + binding.role + ' runtime surface (' + binding.relPath +
          ') digest in the manifest drifts from the on-disk file - the DECLARED ' +
          'harness and the RUNNING harness have diverged. ' + RECOVERY
      );
    }
  }

  return { stale, unresolved, malformed };
}

// ---------------------------------------------------------------------------
// runCheck() -- the --check mode. Regenerate the manifest from the LIVE sources
// in memory, run validateManifest, print each named finding + its recovery line
// to stderr, and exit non-zero on ANY finding. Exit 0 + an OK line on a clean
// repo. Mirrors build-orchestration-projection.cjs runCheck. ZERO Brain/network
// calls (Part 8).
// ---------------------------------------------------------------------------
function runCheck() {
  const manifest = buildManifest();
  const { stale, unresolved, malformed } = validateManifest(manifest);
  const all = [...stale, ...unresolved, ...malformed];
  if (all.length) {
    console.error(all.join('\n'));
    console.error(
      'Recovery: regenerate the manifest, then re-stage it: ' +
        'node scripts/build-harness-manifest.cjs'
    );
    process.exit(1);
    return;
  }
  console.log('harness-manifest: OK');
}

// ---------------------------------------------------------------------------
// writeManifest() -- the default + --refresh write path: re-derive the digests
// from the live sources and write the artifact (idempotent). --refresh is the
// manifest's analogue of the connector --refresh-names: it re-reads the sources,
// re-digests, and re-writes, which is a byte-identical no-op when nothing
// changed.
// ---------------------------------------------------------------------------
function writeManifest() {
  const manifest = buildManifest();
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(MANIFEST_PATH, serializeManifest(manifest));
  console.log(
    'Wrote data/harness-manifest.json (' + manifest.maps.length + ' map entries: ' +
      manifest.maps.map((e) => e.role).join(', ') + '; ' +
      manifest.runtime_surfaces.length + ' runtime surfaces: ' +
      manifest.runtime_surfaces.map((e) => e.role).join(', ') + ')'
  );
}

// ---------------------------------------------------------------------------
// main() -- the 3-branch entry: default write / --check / --refresh.
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--check')) {
    runCheck();
    return;
  }

  // --refresh re-derives the digests + re-writes (idempotent). The default
  // branch is the same write path; --refresh is named for parity with the
  // connector generator's --refresh-names idiom.
  writeManifest();
}

if (require.main === module) {
  main();
} else {
  module.exports = {
    buildManifest,
    buildMapEntry,
    buildSurfaceEntry,
    serializeManifest,
    validateManifest,
    digestBytes,
    primaryArrayCount,
    MAP_BINDINGS,
    RUNTIME_SURFACE_BINDINGS,
    NODE_FIELD_ALLOWLIST,
    ENTRY_FIELD_ALLOWLIST,
    MANIFEST_PATH,
  };
}
