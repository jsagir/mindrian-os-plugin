'use strict';
/*
 * build-harness-runtime-manifest.cjs -- declare the RUNTIME surfaces of the agent
 * harness (Phase 201-01, SEED-032).
 * =========================================================================
 * The existing data/harness-manifest.json is a LOCKED 3-MAP DIGEST over the three
 * DATA maps (posture / wiring / ranked_next_reach) and is Part-8-guarded against
 * field additions. SEED-032's framing (Agent = Model + Harness) also wants the
 * RUNTIME surfaces declared -- the code the harness runs on: the runChain spine, the
 * decide() engine, the statusline cockpit, the brain-orchestration reader. Those are
 * CODE, not data maps, so they get their OWN sibling manifest here rather than
 * polluting the locked 3-map digest.
 *
 * This manifest is a DIGEST descriptor: it names each runtime surface as
 * { role, path, digest(sha256) } -- machinery metadata (a fixed-length fingerprint),
 * NEVER the file contents. A digest changes iff the surface file's bytes change, so
 * `--check` becomes a drift tripwire: the declared harness and the on-disk harness
 * cannot silently diverge.
 *
 * LOCAL only -- no Brain wire, no network. Node built-ins only (fs, path, crypto).
 * 3-branch main mirrors build-harness-manifest.cjs: default write / --check / --refresh.
 * No em-dashes.
 */

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const REPO_ROOT = path.resolve(__dirname, '..');
const MANIFEST_REL = 'data/harness-runtime-manifest.json';
const MANIFEST_PATH = path.join(REPO_ROOT, MANIFEST_REL);

const GENERATED_NOTE = 'GENERATED by scripts/build-harness-runtime-manifest.cjs - do not edit by hand';
const TIER_OP = 'mindrian-operation';
const MANIFEST_VERSION = 1;

// The runtime surfaces the harness is built on. role -> the code file that IS that
// surface. Digest-only (no source_count: these are code, not arrays). Additive: a
// future surface appends one { role, relPath } binding here.
const SURFACE_BINDINGS = Object.freeze([
  { role: 'orchestration_spine', relPath: 'lib/core/chain-executor.cjs' },
  { role: 'decide_engine', relPath: 'lib/core/navigation-engine.cjs' },
  { role: 'cockpit', relPath: 'lib/statusline/cockpit-renderer.cjs' },
  { role: 'brain_orchestration', relPath: 'lib/core/directive-envelope.cjs' },
]);

// Serialized-field allowlists (mirrors the sibling generator's Part-8 discipline:
// a key outside these is a candidate user-content channel and MUST NOT appear).
const NODE_FIELD_ALLOWLIST = Object.freeze(['generated_note', 'methodology_tier', 'version', 'surfaces']);
const ENTRY_FIELD_ALLOWLIST = Object.freeze(['role', 'path', 'digest']);

function readBytes(p) {
  try { return fs.readFileSync(p); } catch (_e) { return null; }
}

function digestBytes(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

// One { role, path, digest } surface entry. A missing surface yields the empty-bytes
// sentinel digest (byte-stable), so the manifest stays stable and --check flags the
// absence as UNRESOLVED rather than the generator throwing.
function buildSurfaceEntry(binding) {
  const buf = readBytes(path.join(REPO_ROOT, binding.relPath));
  return {
    role: binding.role,
    path: binding.relPath,
    digest: buf ? digestBytes(buf) : digestBytes(Buffer.from('')),
  };
}

function buildManifest() {
  return {
    generated_note: GENERATED_NOTE,
    methodology_tier: TIER_OP,
    version: MANIFEST_VERSION,
    surfaces: SURFACE_BINDINGS.map(buildSurfaceEntry),
  };
}

function serializeManifest(manifest) {
  const clean = {
    generated_note: manifest.generated_note,
    methodology_tier: manifest.methodology_tier,
    version: manifest.version,
    surfaces: (Array.isArray(manifest.surfaces) ? manifest.surfaces : []).map((s) => ({
      role: s.role,
      path: s.path,
      digest: s.digest,
    })),
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// validateManifest() -- the 3-mode drift taxonomy, mirroring the sibling generator.
//   STALE      -- serialized regeneration differs byte-for-byte from the committed file.
//   UNRESOLVED -- a declared surface path does not exist on disk.
//   MALFORMED  -- an entry is missing a required key, OR the surfaces set is not
//                 exactly the declared roles (an extra/missing surface).
function validateManifest() {
  const stale = [];
  const unresolved = [];
  const malformed = [];

  const regenerated = serializeManifest(buildManifest());
  const committed = readBytes(MANIFEST_PATH);
  if (committed === null) {
    stale.push(MANIFEST_REL + ' is missing. Run: node scripts/build-harness-runtime-manifest.cjs');
  } else if (committed.toString('utf8') !== regenerated) {
    stale.push(MANIFEST_REL + ' is STALE. Run: node scripts/build-harness-runtime-manifest.cjs');
  }

  for (const b of SURFACE_BINDINGS) {
    if (!fs.existsSync(path.join(REPO_ROOT, b.relPath))) {
      unresolved.push('surface path does not exist: ' + b.relPath + ' (role ' + b.role + ')');
    }
  }

  // MALFORMED: parse the committed file and check entry shape + exact role set.
  if (committed !== null) {
    let parsed = null;
    try { parsed = JSON.parse(committed.toString('utf8')); } catch (_e) {
      malformed.push(MANIFEST_REL + ' is not valid JSON');
    }
    if (parsed) {
      for (const k of Object.keys(parsed)) {
        if (!NODE_FIELD_ALLOWLIST.includes(k)) malformed.push('top-level key outside allowlist: ' + k);
      }
      const surfaces = Array.isArray(parsed.surfaces) ? parsed.surfaces : [];
      const roles = new Set(surfaces.map((s) => s && s.role));
      for (const b of SURFACE_BINDINGS) {
        if (!roles.has(b.role)) malformed.push('missing declared surface role: ' + b.role);
      }
      for (const s of surfaces) {
        for (const k of Object.keys(s || {})) {
          if (!ENTRY_FIELD_ALLOWLIST.includes(k)) malformed.push('entry key outside allowlist: ' + k);
        }
        for (const req of ENTRY_FIELD_ALLOWLIST) {
          if (!s || typeof s[req] !== 'string' || s[req].length === 0) {
            malformed.push('entry missing required key ' + req);
          }
        }
      }
    }
  }

  return { stale, unresolved, malformed };
}

function runCheck() {
  const { stale, unresolved, malformed } = validateManifest();
  const all = stale.concat(unresolved).concat(malformed);
  if (all.length === 0) {
    process.stdout.write('harness-runtime-manifest: OK\n');
    return 0;
  }
  for (const e of all) process.stderr.write(e + '\n');
  return 1;
}

function runWrite() {
  fs.writeFileSync(MANIFEST_PATH, serializeManifest(buildManifest()));
  process.stdout.write('Wrote ' + MANIFEST_REL + ' (' + SURFACE_BINDINGS.length + ' runtime surfaces)\n');
  return 0;
}

function main(argv) {
  if (argv.includes('--check')) return runCheck();
  return runWrite(); // default write (and --refresh is a re-write, same effect)
}

module.exports = {
  buildManifest, serializeManifest, validateManifest, buildSurfaceEntry,
  SURFACE_BINDINGS, NODE_FIELD_ALLOWLIST, ENTRY_FIELD_ALLOWLIST, MANIFEST_REL, main,
};

if (require.main === module) {
  process.exit(main(process.argv.slice(2)));
}
