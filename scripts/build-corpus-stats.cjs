#!/usr/bin/env node
'use strict';

/*
 * Phase 186-01 - Corpus-stats artifact generator (the single source of truth
 * for the three asserted corpus magnitudes, Canon D1).
 *
 * Implements: CORPUS-01. Renders docs/CORPUS-STATS.generated.md +
 * data/corpus-stats.generated.json from the committed local source
 * data/corpus-stats-source.json. The artifact is GENERATED and never
 * hand-edited - exactly how data/connector-registry.json is rendered from
 * frontmatter by scripts/build-connector-registry.cjs.
 *
 * Canon Part 7 (Reuse Before Build): this MIRRORS
 * scripts/build-connector-registry.cjs - the REPO_ROOT / path-constant idiom,
 * the GENERATED_NOTE stamp, the deterministic serializer (JSON.stringify with
 * (null, 2) + a trailing newline so the Plan 02 --check byte-compare is
 * deterministic), and the require.main === module guard exporting the pure
 * functions for tests.
 *
 * Canon Part 8 (The Graph Boundary) / threat T-186-01: this generator requires
 * ONLY the two node built-ins below (the filesystem + path modules). It imports
 * no Brain MCP client and no network module of any kind (no remote HTTP client,
 * no socket library) - the magnitudes come from the COMMITTED local source file,
 * NEVER a live Brain query on the hot path (Canon D5). A build/commit can never
 * hang on a Render cold-start and never egresses. The proof is a grep over this
 * file for the forbidden import tokens, which returns nothing (see the Task 2
 * done-criteria in the plan, and the phase verification block).
 *
 * Usage:
 *   node scripts/build-corpus-stats.cjs
 *       read data/corpus-stats-source.json -> write
 *       docs/CORPUS-STATS.generated.md + data/corpus-stats.generated.json
 *   node scripts/build-corpus-stats.cjs --check
 *       (reserved for Plan 02 - the stale-artifact byte-compare tripwire)
 */

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');

const SOURCE_PATH = path.join(REPO_ROOT, 'data', 'corpus-stats-source.json');
const DATA_DIR = path.join(REPO_ROOT, 'data');
const DOCS_DIR = path.join(REPO_ROOT, 'docs');
const MD_PATH = path.join(DOCS_DIR, 'CORPUS-STATS.generated.md');
const JSON_PATH = path.join(DATA_DIR, 'corpus-stats.generated.json');

const GENERATED_NOTE =
  'GENERATED by scripts/build-corpus-stats.cjs - do not hand-edit';

// ---------------------------------------------------------------------------
// loadSource() - read + parse the committed magnitude source. This is the ONLY
// input. It is a local file read; it makes ZERO Brain/network calls (Part 8).
// ---------------------------------------------------------------------------
function loadSource() {
  return JSON.parse(fs.readFileSync(SOURCE_PATH, 'utf8'));
}

// Deterministic grouped-thousands formatter (locale-independent so the rendered
// bytes are stable across machines for the Plan 02 byte-compare). 27904 -> "27,904".
function groupThousands(n) {
  const s = String(n);
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, ',');
}

// ---------------------------------------------------------------------------
// renderMarkdown(src) - deterministic markdown for the rendered single source
// of truth. The first body line after the H1 is the GENERATED_NOTE stamp (an
// HTML comment plus a visible "do not hand-edit" line). It asserts EXACTLY the
// three magnitudes (Canon D1) and asserts NO directional sub-count as fact
// (Canon D2). Hyphens only, never em-dashes.
// ---------------------------------------------------------------------------
function renderMarkdown(src) {
  const m = src.magnitudes;
  const nodes = groupThousands(m.neo4j_nodes);
  const frameworks = groupThousands(m.frameworks);
  const vectors = groupThousands(m.pinecone_vectors);
  // Dimensionality is an embedding-width label (canonically "1024-dim"), not a
  // corpus magnitude, so it is NOT grouped-thousands - it reads 1024, not 1,024.
  const dim = String(src.pinecone_dim);

  const lines = [
    '# Corpus Stats (Generated)',
    '',
    '<!-- ' + GENERATED_NOTE + ' -->',
    '> ' + GENERATED_NOTE + '. This file is rendered from data/corpus-stats-source.json by scripts/build-corpus-stats.cjs. Edit the source, not this file.',
    '',
    'The single source of truth for MindrianOS corpus magnitudes. These three numbers are the ONLY asserted corpus magnitudes (Canon D1), rendered from a committed local source by a Brain-free local generator (Canon Part 8 / D5: no live Brain query on the hot path).',
    '',
    '## Asserted magnitudes',
    '',
    '| Magnitude | Value |',
    '| --------- | ----- |',
    '| Neo4j nodes | ' + nodes + ' |',
    '| Frameworks | ' + frameworks + ' |',
    '| Pinecone vectors (pws-brain, ' + dim + '-dim) | ' + vectors + ' |',
    '',
    'Read date: ' + src.read_date + '.',
    '',
    '## Directional sub-counts',
    '',
    'Directional sub-counts are NOT asserted here (Canon D2). Sub-counts (teaching-graph core, MethodologyChunk substrate, per-namespace vector splits, relationship counts) are directional only, zero source-of-truth, admin-gated, and never enforced by the tripwire. They are deliberately omitted.',
    '',
  ];
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// serializeArtifactJson(src) - the machine-readable sibling. JSON.stringify
// with (null, 2) + a trailing newline (the connector serializer discipline, so
// the Plan 02 --check byte-compare is deterministic). Carries ONLY the three
// magnitudes + dim + the stamp + read_date; no directional sub-count.
// ---------------------------------------------------------------------------
function serializeArtifactJson(src) {
  const clean = {
    generated_note: GENERATED_NOTE,
    read_date: src.read_date,
    magnitudes: {
      neo4j_nodes: src.magnitudes.neo4j_nodes,
      frameworks: src.magnitudes.frameworks,
      pinecone_vectors: src.magnitudes.pinecone_vectors,
    },
    pinecone_dim: src.pinecone_dim,
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// main() - three-branch (mirrors build-connector-registry.cjs).
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--check')) {
    // Reserved for Plan 02 (the stale-artifact byte-compare tripwire). For now
    // re-render in memory and exit 0 - Plan 02 owns the real --check logic.
    const src = loadSource();
    renderMarkdown(src);
    serializeArtifactJson(src);
    console.log('corpus-stats: --check stub (Plan 02 owns the tripwire)');
    return;
  }

  // Default: write BOTH artifact files.
  const src = loadSource();
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.mkdirSync(DOCS_DIR, { recursive: true });
  fs.writeFileSync(MD_PATH, renderMarkdown(src));
  fs.writeFileSync(JSON_PATH, serializeArtifactJson(src));
  console.log('Wrote docs/CORPUS-STATS.generated.md + data/corpus-stats.generated.json');
  console.log(
    '  magnitudes: ' +
      groupThousands(src.magnitudes.neo4j_nodes) + ' nodes / ' +
      groupThousands(src.magnitudes.frameworks) + ' frameworks / ' +
      groupThousands(src.magnitudes.pinecone_vectors) + ' Pinecone vectors (' +
      String(src.pinecone_dim) + '-dim)'
  );
}

module.exports = { loadSource, renderMarkdown, serializeArtifactJson };

if (require.main === module) {
  main();
}
