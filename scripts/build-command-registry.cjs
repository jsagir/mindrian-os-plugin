#!/usr/bin/env node
'use strict';

/*
 * Phase 122-02 - Command registry generator + drift tripwire + names refresh.
 *
 * Implements: WORKFLOW-122-02, WORKFLOW-122-03, WORKFLOW-122-10.
 *
 * Reliability rule 2 (.planning/WORKFLOW-LAYER-SPEC.md): the framework <->
 * command mapping lives in ONE place -- the `frameworks:` key in each
 * commands/*.md frontmatter -- and everything downstream is GENERATED from it
 * and CI-checked against it. `data/command-registry.json` is built from
 * frontmatter; a `--check` run regenerates it in memory and exits non-zero on
 * a stale on-disk registry OR an unresolvable framework name (one not in the
 * FEEDS_INTO-linked Brain framework slice snapshotted to
 * `data/framework-names.json`).
 *
 * Canon Part 7 (Reuse Before Build): this REUSES the hand-rolled
 * line-walk frontmatter-parse pattern (scripts/frontmatter-schema-validator.cjs
 * mirrors it via gray-matter; we hand-roll here per CLAUDE.md "no new deps"),
 * the static-catalog pattern (lib/core/integration-registry.cjs), the Brain
 * chokepoint (lib/core/brain-client.cjs), and the CI surface (the existing
 * .git/hooks/pre-commit bash guard + the Feynman runner). It adds NO GitHub
 * Actions, NO gray-matter, NO zod, NO new dependency.
 *
 * Canon Part 8 (The Graph Boundary): the registry is plugin-local, validated
 * AGAINST Brain framework names, NEVER written back. The ONLY Brain touch is a
 * read-only brain.query in --refresh-names at BUILD time -- the query carries
 * only generic `:Framework` node names (a methodology handle, never user
 * data), and there is no write Cypher anywhere in this file. The generator and
 * any resolver never need the Brain at runtime.
 *
 * Usage:
 *   node scripts/build-command-registry.cjs
 *       scan commands/*.md -> write data/command-registry.json ;
 *       exit 1 on an unresolvable framework
 *   node scripts/build-command-registry.cjs --check
 *       regenerate in memory ; exit 1 if on-disk JSON is stale OR a framework
 *       is unresolvable ; print a one-line recovery command in stderr
 *   node scripts/build-command-registry.cjs --refresh-names
 *       read-only brain.query -> rewrite data/framework-names.json
 *       (build-time only ; graceful no-op if the Brain is unreachable)
 */

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const COMMANDS_DIR = path.join(REPO_ROOT, 'commands');
const DATA_DIR = path.join(REPO_ROOT, 'data');
const REGISTRY_PATH = path.join(DATA_DIR, 'command-registry.json');
const FW_NAMES_PATH = path.join(DATA_DIR, 'framework-names.json');

// Phase 104.1: JTBD taxonomy is the single source of truth for jtbd_label +
// jtbd_summary content per Canon Part 7 (reuse over build). The build script
// derives both at registry-build time from `serves_jtbd[0]` -- never authored
// per-command in frontmatter. The only NET-NEW content authored per-command is
// the `teaching` string (1-2 sentences, 50-300 chars, Larry-voice, no em-dashes
// per project hard rule; see docs/COMMAND-FRONTMATTER.md for the schema).
const taxonomyPath = path.join(REPO_ROOT, 'lib', 'hmi', 'jtbd-taxonomy.json');
let taxonomyById = {};
try {
  const taxonomy = JSON.parse(fs.readFileSync(taxonomyPath, 'utf8'));
  taxonomyById = Object.fromEntries(
    (Array.isArray(taxonomy && taxonomy.entries) ? taxonomy.entries : []).map((e) => [e.id, e])
  );
} catch (_e) {
  // Taxonomy missing -> jtbd_label + jtbd_summary derive to null for every
  // command. Phase 125 Plan 05 ranker fails-closed on null per its D6.
  taxonomyById = {};
}

function _capitalizeJtbdLabel(id) {
  // 'find-bottleneck' -> 'Find Bottleneck'.
  return id
    .split('-')
    .map((w) => (w.length > 0 ? w.charAt(0).toUpperCase() + w.slice(1) : w))
    .join(' ');
}

const GENERATED_NOTE =
  'GENERATED by scripts/build-command-registry.cjs - do not edit by hand';

// The FEEDS_INTO traversal that snapshots the framework-name allowlist. This
// is the ONLY Cypher this file ever runs, it is read-only, and it carries no
// user-specific strings -- only the generic `:Framework` label. Per the
// research caveat: the ~105-name FEEDS_INTO-linked subset, NOT all 748
// :Framework nodes (junk like "Amazon" / "Charles Kirschbaum" must not enter
// the allowlist).
const FW_NAMES_CYPHER =
  'MATCH (f:Framework) WHERE (f)-[:FEEDS_INTO]-() RETURN f.name AS name';

// ---------------------------------------------------------------------------
// Hand-rolled frontmatter parser (mirrors scripts/frontmatter-schema-validator
// .cjs / lib/core/frontmatter-schemas.cjs -- the YAML-ish slice commands use).
// Handles:  `key: value`  |  `key: ["a","b"]` (JSON.parse)  |  `key:` + indented
// `- item` dash list  |  strips surrounding quotes  |  `key: null` -> null  |
// `key: true|false` -> boolean.
// ---------------------------------------------------------------------------
function parseFrontmatter(md) {
  if (typeof md !== 'string') return {};
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md);
  if (!m) return {};
  const out = {};
  let key = null;
  for (const rawLine of m[1].split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
    if (kv) {
      key = kv[1];
      const v = kv[2].trim();
      if (v === '') {
        // `key:` with nothing after it -> an empty list, or a dash list to
        // follow on indented lines below.
        out[key] = [];
      } else if (v === 'null' || v === '~') {
        out[key] = null;
      } else if (v === 'true' || v === 'false') {
        out[key] = v === 'true';
      } else if (v.startsWith('[')) {
        try {
          out[key] = JSON.parse(v);
        } catch (_e) {
          // Fall back to a stripped raw string if it is not valid JSON.
          out[key] = v.replace(/^["']|["']$/g, '');
        }
      } else {
        out[key] = v.replace(/^["']|["']$/g, '');
      }
    } else if (key && /^\s*-\s+/.test(line)) {
      if (!Array.isArray(out[key])) out[key] = [];
      out[key].push(line.replace(/^\s*-\s+/, '').replace(/^["']|["']$/g, ''));
    }
    // Any other line (blank, comment `# ...`, deeper indentation) is ignored.
  }
  return out;
}

// ---------------------------------------------------------------------------
// Load the committed framework-name allowlist: the FEEDS_INTO-linked Brain
// slice (`framework_names`) UNION a small `curated_extras` whitelist of
// legitimate :Framework node names that exist in the Brain but are not yet
// FEEDS_INTO-linked (the brain-cleanup project adds those edges over time).
// Per the research: the allowlist "must be the FEEDS_INTO-linked slice (or a
// curated whitelist), NOT all 748 names" -- `curated_extras` is the curated
// whitelist clause. Junk like "Amazon" / "Charles Kirschbaum" is NEVER added.
// ---------------------------------------------------------------------------
function loadFrameworkNames() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const names = Array.isArray(raw && raw.framework_names) ? raw.framework_names : [];
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return new Set([...names, ...extras]);
  } catch (_e) {
    // No snapshot on disk yet -> empty allowlist. The default run will then
    // flag every declared framework as unresolvable, which is the correct
    // "nothing is validated, refuse to write" behavior.
    return new Set();
  }
}

// Read the existing `curated_extras` block (if any) so --refresh-names
// preserves it when it rewrites the FEEDS_INTO subset.
function loadCuratedExtras() {
  try {
    const raw = JSON.parse(fs.readFileSync(FW_NAMES_PATH, 'utf8'));
    const extras = Array.isArray(raw && raw.curated_extras) ? raw.curated_extras : [];
    return extras.slice();
  } catch (_e) {
    return [];
  }
}

// ---------------------------------------------------------------------------
// buildRegistry() -- scan commands/*.md (sorted), parse frontmatter, build the
// commands[] array, the inverse framework_index, and collect _unresolved for
// any framework not in the allowlist. Returns the registry object PLUS the
// non-serialized `_unresolved` field (callers strip it before writing).
// ---------------------------------------------------------------------------
function buildRegistry() {
  const fwNames = loadFrameworkNames();
  const files = fs.readdirSync(COMMANDS_DIR).filter((f) => f.endsWith('.md')).sort();
  const commands = [];
  const frameworkIndex = {};
  const unresolved = [];

  const missingServesJtbd = [];
  for (const f of files) {
    const fm = parseFrontmatter(fs.readFileSync(path.join(COMMANDS_DIR, f), 'utf8'));
    const name = typeof fm.name === 'string' && fm.name ? fm.name : f.replace(/\.md$/, '');
    const command = '/mos:' + name;
    const kind = typeof fm.kind === 'string' && fm.kind ? fm.kind : 'utility';
    const frameworks = Array.isArray(fm.frameworks) ? fm.frameworks.slice() : [];
    const produces = fm.produces === undefined ? null : fm.produces;
    const inputs = Array.isArray(fm.inputs) ? fm.inputs.slice() : [];
    const autonomousSafe = fm.autonomous_safe === true || fm.autonomous_safe === 'true';
    const bodyShape = fm.body_shape ? fm.body_shape : null;
    const servesJtbd = Array.isArray(fm.serves_jtbd) ? fm.serves_jtbd.slice() : [];

    // Phase 104.1: extract `teaching` (Larry-voice 1-2 sentence explanation of
    // when to invoke this command). Reads `frontmatter.teaching` (locally
    // bound as `fm.teaching` per the existing buildRegistry pattern). Null
    // when absent; Plan 02 fills content.
    const teaching =
      typeof fm.teaching === 'string' && fm.teaching.trim() !== ''
        ? fm.teaching.trim()
        : null;

    // Phase 104.1: derive jtbd_label + jtbd_summary from the taxonomy via
    // `serves_jtbd[0]` per Canon Part 7. NEVER authored per-command.
    const jtbdId = servesJtbd.length > 0 ? servesJtbd[0] : null;
    const taxonomyEntry = jtbdId ? taxonomyById[jtbdId] : null;
    const jtbdLabel = jtbdId ? _capitalizeJtbdLabel(jtbdId) : null;
    const jtbdSummary =
      taxonomyEntry && typeof taxonomyEntry.one_line === 'string'
        ? taxonomyEntry.one_line
        : null;

    if (servesJtbd.length === 0) missingServesJtbd.push(command);

    for (const fw of frameworks) {
      if (!fwNames.has(fw)) unresolved.push({ command, framework: fw });
      if (!Array.isArray(frameworkIndex[fw])) frameworkIndex[fw] = [];
      frameworkIndex[fw].push(command);
    }

    commands.push({
      command,
      kind,
      frameworks,
      produces,
      inputs,
      autonomous_safe: autonomousSafe,
      body_shape: bodyShape,
      serves_jtbd: servesJtbd,
      teaching,
      jtbd_label: jtbdLabel,
      jtbd_summary: jtbdSummary,
    });
  }

  return {
    ontology_ref: 'data/framework-names.json',
    generated_note: GENERATED_NOTE,
    commands,
    framework_index: frameworkIndex,
    curated_chains: [],
    _unresolved: unresolved,
    _missingServesJtbd: missingServesJtbd,
  };
}

// Serialize the registry exactly the way the on-disk file is written, so the
// --check byte-compare is deterministic. Strips the non-serialized
// `_unresolved` field.
function serializeRegistry(reg) {
  const clean = {
    ontology_ref: reg.ontology_ref,
    generated_note: reg.generated_note,
    commands: reg.commands,
    framework_index: reg.framework_index,
    curated_chains: reg.curated_chains,
  };
  return JSON.stringify(clean, null, 2) + '\n';
}

// ---------------------------------------------------------------------------
// --refresh-names: read-only brain.query for the FEEDS_INTO-linked name
// slice -> rewrite data/framework-names.json. BUILD-TIME ONLY. The ONLY code
// path in this file that touches the Brain, and it is read-only.
// ---------------------------------------------------------------------------
async function refreshNames() {
  // brain-client is required HERE -- inside the --refresh-names branch only.
  // There is no top-level require of brain-client; the generator and --check
  // never load it.
  let brain;
  try {
    brain = require(path.join(REPO_ROOT, 'lib', 'core', 'brain-client.cjs'));
  } catch (_e) {
    console.error('Brain client unavailable -- keeping the committed snapshot');
    process.exit(0);
    return;
  }
  if (!brain.isAvailable || !brain.isAvailable()) {
    console.log('Brain unavailable -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  let result;
  try {
    result = await brain.query(FW_NAMES_CYPHER);
  } catch (_e) {
    console.log('Brain query failed -- keeping the committed snapshot');
    process.exit(0);
    return;
  }
  if (!result || !Array.isArray(result.records)) {
    console.log('Brain returned no usable records -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  const names = [];
  for (const rec of result.records) {
    // brain_query records are plain objects keyed by the RETURN alias.
    const v = rec && (rec.name !== undefined ? rec.name : rec['f.name']);
    if (typeof v === 'string' && v.trim()) names.push(v.trim());
  }
  const deduped = Array.from(new Set(names)).sort((a, b) => a.localeCompare(b));
  if (deduped.length === 0) {
    console.log('Brain returned an empty name list -- keeping the committed snapshot');
    process.exit(0);
    return;
  }

  const curatedExtras = loadCuratedExtras().slice().sort((a, b) => a.localeCompare(b));
  const snapshot = {
    snapshot_note:
      'FEEDS_INTO-linked :Framework names from the Brain (read-only build-time query). Refresh with: node scripts/build-command-registry.cjs --refresh-names',
    snapshot_date: new Date().toISOString().slice(0, 10),
    framework_names: deduped,
    curated_extras_note:
      'Legitimate :Framework node names that exist in the Brain but are not yet FEEDS_INTO-linked. Hand-curated. NOT junk nodes. The allowlist the registry validates against is framework_names UNION curated_extras.',
    curated_extras: curatedExtras,
  };
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(FW_NAMES_PATH, JSON.stringify(snapshot, null, 2) + '\n');
  console.log('Wrote data/framework-names.json (' + deduped.length + ' FEEDS_INTO-linked names)');
}

// ---------------------------------------------------------------------------
// main()
// ---------------------------------------------------------------------------
function main() {
  const argv = process.argv.slice(2);

  if (argv.includes('--refresh-names')) {
    // Async path -- run it and let it call process.exit.
    refreshNames().catch((e) => {
      console.error('refresh-names error: ' + (e && e.message ? e.message : String(e)));
      process.exit(1);
    });
    return;
  }

  const reg = buildRegistry();
  const errs = [];
  if (reg._unresolved.length) {
    const list = reg._unresolved
      .map((u) => u.command + ' -> "' + u.framework + '"')
      .join(', ');
    errs.push('Unresolvable frameworks (not in data/framework-names.json): ' + list);
  }

  if (argv.includes('--check')) {
    const next = serializeRegistry(reg);
    const onDisk = fs.existsSync(REGISTRY_PATH) ? fs.readFileSync(REGISTRY_PATH, 'utf8') : '';
    if (onDisk !== next) {
      errs.push('data/command-registry.json is STALE. Run: node scripts/build-command-registry.cjs');
    }
    // Phase 104.1 Plan 02: teaching-presence tripwire flipped from WARNING
    // to ERROR after the content sweep landed. All 86 commands now carry a
    // non-empty teaching field; any future drift (a command frontmatter
    // losing teaching, or a new command shipped without teaching) fails the
    // build at --check time, matching the Phase 122 stale-registry pattern.
    const missingTeaching = reg.commands
      .filter((c) => !c.teaching || c.teaching.length === 0)
      .map((c) => c.command);
    if (missingTeaching.length > 0) {
      const preview = missingTeaching.slice(0, 5).join(', ');
      const ellipsis = missingTeaching.length > 5 ? '...' : '';
      process.stderr.write(
        '[build-command-registry] ERROR: ' +
          missingTeaching.length +
          ' commands missing teaching field: ' +
          preview +
          ellipsis +
          '\n'
      );
      process.exit(1);
    }
    if (errs.length) {
      console.error(errs.join('\n'));
      console.error('Recovery: fix the command frontmatter (or run --refresh-names), then regenerate: node scripts/build-command-registry.cjs');
      process.exit(1);
    }
    console.log('command-registry: OK');
    return;
  }

  // Default: write the registry, refusing on any unresolvable framework.
  if (errs.length) {
    console.error(errs.join('\n'));
    console.error('Recovery: fix the command frontmatter (or run --refresh-names), then re-run: node scripts/build-command-registry.cjs');
    process.exit(1);
  }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  fs.writeFileSync(REGISTRY_PATH, serializeRegistry(reg));
  console.log('Wrote data/command-registry.json (' + reg.commands.length + ' commands)');

  // Phase 104.1 Plan 01: surface commands without `serves_jtbd` for visibility
  // (per CONTEXT.md Open Question #4 lean: yes, warn at end of build). These
  // commands will have null jtbd_label + null jtbd_summary in the registry;
  // Phase 125 Plan 05 ranker already fails-closed on null per its D6.
  if (Array.isArray(reg._missingServesJtbd) && reg._missingServesJtbd.length > 0) {
    const preview = reg._missingServesJtbd.slice(0, 5).join(', ');
    const ellipsis = reg._missingServesJtbd.length > 5 ? '...' : '';
    process.stderr.write(
      '[build-command-registry] WARNING: ' +
        reg._missingServesJtbd.length +
        ' commands without serves_jtbd (null jtbd_label + jtbd_summary): ' +
        preview +
        ellipsis +
        '\n'
    );
  }
}

if (require.main === module) {
  main();
} else {
  module.exports = { parseFrontmatter, buildRegistry };
}
