function nonEmptyString(v) {
  return typeof v === 'string' && v.trim().length > 0;
}

// claimStanding(db, claimId) -- read-only; never throws.
function claimStanding(db, claimId) {
  const out = {
    claim_id: claimId,
    found: false,
    standing: 'none',
    located: false,
    source_node_ids: [],
    declared_max_rung: null,
    records_total: 0,
  };
  let row;
  try {
    row = db.prepare("SELECT id, type, properties FROM nodes WHERE id = ? AND type = 'claim'").get(claimId);
  } catch (_e) {
    return out;
  }
  if (!row) return out;
  out.found = true;

  const props = parseProperties(row);
  const verification = isPlainObject(props.verification) ? props.verification : {};
  const records = normalizeRecords(Array.isArray(verification.records) ? verification.records : []);
  out.records_total = records.length;
  let askSeen = false;
  for (const rec of records) {
    if (rec.method === 'ask') askSeen = true;
    if (Number.isInteger(rec.rung) && rec.rung >= 1) {
      if (out.declared_max_rung === null || rec.rung > out.declared_max_rung) out.declared_max_rung = rec.rung;
      const info = rungInfo(rec.rung);
      if (info && info.id === 'model_counter_argument') askSeen = true;
    }
  }

  // Outbound provenance edges only (never inbound, never other types).
  const types = Array.from(PROVENANCE_EDGE_TYPES);
  let edges = [];
  try {
    edges = db.prepare(
      'SELECT target, properties FROM edges WHERE source = ? AND type IN (' + types.map(() => '?').join(',') + ')'
    ).all(claimId, ...types) || [];
  } catch (_e) {
    edges = [];
  }
  const sourceIds = [];
  let located = false;
  for (const edge of edges) {
    let target;
    try {
      target = db.prepare('SELECT id, properties FROM nodes WHERE id = ?').get(edge.target);
    } catch (_e) {
      target = null;
    }
    if (!target) continue;
    const tp = parseProperties(target);
    if (!nonEmptyString(tp.url) || !nonEmptyString(tp.retrieved_at)) continue;
    if (sourceIds.indexOf(target.id) === -1) sourceIds.push(target.id);
    const ep = parseProperties(edge);
    if (nonEmptyString(tp.locator) || nonEmptyString(ep.locator)) located = true;
  }
  out.source_node_ids = sourceIds.slice(0, 10);
  if (sourceIds.length > 0) {
    out.standing = located ? 'located_source' : 'source_edge';
    out.located = located;
  } else if (askSeen) {
    out.standing = 'model_only';
  }
  return out;
}

// readStandingPortrait(db) -- read-only room counts by standing, for the pulled
// portrait (D-16). Separate from readVerificationPortrait on purpose: that
// reader's output is pinned byte-for-byte by the 358 suites. Counts only, never
// a score; held = claims whose review_status is needs_evidence.
function readStandingPortrait(db) {
  const out = {
    claims_by_standing: { located_source: 0, source_edge: 0, model_only: 0, none: 0 },
    held: 0,
    records_total: 0,
  };
  let rows;
  try {
    rows = db.prepare("SELECT id, review_status FROM nodes WHERE type = 'claim'").all();
  } catch (_e) {
    return out;
  }
  for (const row of rows || []) {
    const st = claimStanding(db, row.id);
    const key = Object.prototype.hasOwnProperty.call(out.claims_by_standing, st.standing) ? st.standing : 'none';
    out.claims_by_standing[key] += 1;
    out.records_total += st.records_total;
    if (row.review_status === 'needs_evidence') out.held += 1;
  }
  return out;
}

// readReadinessCounts(db) -- HARNESS-11 counting half (369.2-27, annex C16, brief test 22). Read-only counts of
// claims apart from every other confirmed node type, so "confirmed" never means "confirmed whitespace zones".
// The session review counted 137 confirmed nodes that were auto-generated whitespace zones while zero claims
// were confirmed. These field names are the contract plan 369.4's export banner reads; do not rename them.
//
// READINESS_CLAIM_TYPES are the claim node types: transitions.cjs:47 TRUTH_CLAIM_TYPES minus decision,
// opportunity, assumption and SyntheticExpert (those are other truth-bearing nodes, not claims). EvidenceClaim
// is excluded on purpose: it carries untrusted external web bytes and is non-promotable (transitions.cjs
// NON_PROMOTABLE), so it can never be a confirmed claim. Confirmed means review_status 'confirmed'.
// A db without review_status (a legacy room) answers zeros with schema_note 'no_review_status'. One SELECT, no
// write, over the caller's handle (a read-only handle is fine).
const READINESS_CLAIM_TYPES = Object.freeze(['claim', 'CausalClaim']);

function readReadinessCounts(db) {
  const out = { claims_total: 0, confirmed_claim_count: 0, confirmed_other_by_type: {}, confirmed_other_count: 0 };
  let rows;
  try {
    const cols = db.prepare('PRAGMA table_info(nodes)').all() || [];
    const hasStatus = cols.some((c) => c && c.name === 'review_status');
    if (!hasStatus) {
      out.schema_note = 'no_review_status';
      return out;
    }
    rows = db.prepare('SELECT type, review_status, COUNT(*) AS c FROM nodes GROUP BY type, review_status').all();
  } catch (_e) {
    out.schema_note = 'no_review_status';
    return out;
  }
  for (const row of rows || []) {
    const n = Number(row.c) || 0;
    const isClaim = READINESS_CLAIM_TYPES.indexOf(row.type) !== -1;
    const confirmed = row.review_status === 'confirmed';
    if (isClaim) {
      out.claims_total += n;
      if (confirmed) out.confirmed_claim_count += n;
    } else if (confirmed) {
      out.confirmed_other_by_type[row.type] = (out.confirmed_other_by_type[row.type] || 0) + n;
      out.confirmed_other_count += n;
    }
  }
  return out;
}

// standingMeetsFloor(standing, floorId) -> {met, requirement}
function standingMeetsFloor(standing, floorId) {
  const requirement = Object.prototype.hasOwnProperty.call(FLOOR_WORDS, floorId) ? FLOOR_WORDS[floorId] : '';
  const sourceLike = standing === 'source_edge' || standing === 'located_source';
  let met = false;
  switch (floorId) {
    case 'unchecked':
    case 'recall':
      met = true;
      break;
    case 'model_internal':
      met = standing === 'model_only' || sourceLike;
      break;
    case 'secondary_document':
      met = sourceLike;
      break;
    case 'primary_source_located':
      met = standing === 'located_source';
      break;
    default:
      met = false; // person (not recordable yet) and anything unknown fail shut
  }
  return { met: met, requirement: requirement };
}

/**
 * listClaimsForChecking(db, {query, limit}) -- a search-by-text list so an
 * officer in a new session can reopen a claim without knowing its id
 * (Pitfall 3). Newest first, case-insensitive substring match.
 */
function listClaimsForChecking(db, opts) {
  const options = isPlainObject(opts) ? opts : {};
  let query = typeof options.query === 'string' ? options.query.trim().toLowerCase() : '';
  if (query.length > 200) query = query.slice(0, 200);
  let limit = Number.isInteger(options.limit) ? options.limit : 20;
  if (limit < 1) limit = 1;
  if (limit > 100) limit = 100;
  // Phase 365: optional standing filter. A value outside STANDING_IDS fails shut
  // (no rows), never "all rows".
  const standingFilter = options.standing === undefined || options.standing === null ? null : options.standing;
  if (standingFilter !== null && STANDING_IDS.indexOf(standingFilter) === -1) {
    return { ok: true, total_matched: 0, claims: [] };
  }

  let rows;
  try {
    rows = db.prepare("SELECT id, properties, review_status FROM nodes WHERE type = 'claim' ORDER BY rowid DESC").all();
  } catch (_e) {
    return { ok: true, total_matched: 0, claims: [] };
  }

  const kept = [];
  for (const row of rows || []) {
    const props = parseProperties(row);
    const text = typeof props.text === 'string' ? props.text : '';
    if (query && !text.toLowerCase().includes(query) && !String(row.id).toLowerCase().includes(query)) continue;
    const standing = claimStanding(db, row.id).standing;
    if (standingFilter !== null && standing !== standingFilter) continue;
    kept.push({ row: row, props: props, text: text, standing: standing });
  }
  const totalMatched = kept.length;
  const claims = kept.slice(0, limit).map((entry) => {
    const verification = isPlainObject(entry.props.verification) ? entry.props.verification : {};
    const records = Array.isArray(verification.records) ? verification.records : [];
    const preview = entry.text.length <= 120 ? entry.text : entry.text.slice(0, 117) + '...';
    return {
      claim_id: entry.row.id,
      text_preview: preview,
      review_status: entry.row.review_status,
      checking_status: deriveCheckStatus(records),
      records_total: records.length,
      standing: entry.standing,
    };
  });
  return { ok: true, total_matched: totalMatched, claims: claims };
}

/**
 * Read the B1 room portrait. Counts are descriptive and deliberately are not
 * collapsed into a score or a truth verdict (Canon Part 12). Status is
 * ALWAYS re-derived from the stored records (never read from the legacy
 * status field), so old latest-wins data is re-read under the sticky rule.
 */
function readVerificationPortrait(db) {
  const recordsByRung = {};
  for (let i = 1; i <= VERIFICATION_RUNGS.length; i += 1) recordsByRung[String(i)] = 0;
  recordsByRung.unknown = 0;

  const out = {
    claims_total: 0,
    claims_unchecked: 0,
    claims_checked: 0,
    claims_disputed: 0,
    claims_inconclusive: 0,
    records_total: 0,
    records_by_result: { supports: 0, contradicts: 0, inconclusive: 0 },
    records_by_rung: recordsByRung,
  };
  let rows;
  try {
    rows = db.prepare("SELECT properties FROM nodes WHERE type = 'claim'").all();
  } catch (_e) {
    return out;
  }
  for (const row of rows || []) {
    out.claims_total += 1;
    const props = parseProperties(row);
    const verification = isPlainObject(props.verification) ? props.verification : {};
    const storedRecords = Array.isArray(verification.records) ? verification.records : [];
    const status = deriveCheckStatus(storedRecords);
    if (status === 'unchecked') out.claims_unchecked += 1;
    if (status === 'checked') out.claims_checked += 1;
    if (status === 'disputed') out.claims_disputed += 1;
    if (status === 'inconclusive') out.claims_inconclusive += 1;
    for (const record of normalizeRecords(storedRecords)) {
      out.records_total += 1;
      if (Object.prototype.hasOwnProperty.call(out.records_by_result, record.result)) {
        out.records_by_result[record.result] += 1;
      }
      if (Number.isInteger(record.rung) && record.rung >= 1) {
        const key = String(record.rung);
        out.records_by_rung[key] = (out.records_by_rung[key] || 0) + 1;
      } else {
        out.records_by_rung.unknown += 1;
      }
    }
  }
  return out;
}

// renderPortraitLines / renderClaimViewLines / renderClaimListLines -- the
// ONE place these render strings are written; the CLI (358-03) and the MCP
// tools (358-04) both print these lines verbatim. Plain ASCII, hyphens only,
// the word "verified" never appears (Separation from approval).
function renderPortraitLines(portrait, standingPortrait) {
  const lines = [];
  lines.push('Checking record across this room (counts only)');
  lines.push('  checked: ' + portrait.claims_checked);
  lines.push('  disputed: ' + portrait.claims_disputed);
  lines.push('  inconclusive: ' + portrait.claims_inconclusive);
  lines.push('  unchecked (no checking record yet): ' + portrait.claims_unchecked);
  lines.push('  claims in this room: ' + portrait.claims_total);
  lines.push(
    '  checks recorded: ' + portrait.records_total +
    ' (supports ' + portrait.records_by_result.supports +
    ', contradicts ' + portrait.records_by_result.contradicts +
    ', inconclusive ' + portrait.records_by_result.inconclusive + ')'
  );
  const rungKeys = Object.keys(portrait.records_by_rung || {})
    .filter((k) => k !== 'unknown')
    .sort((a, b) => Number(a) - Number(b));
  const byRungParts = rungKeys.map((k) => 'rung ' + k + ': ' + portrait.records_by_rung[k]);
  byRungParts.push('rung unknown: ' + (portrait.records_by_rung.unknown || 0));
  lines.push('  checks by rung: ' + byRungParts.join(', '));
  // Phase 365 (D-16): the optional second argument adds one row per standing and
  // the held row, each naming what would move it. One argument renders exactly
  // the 358 lines. The closing line stays last.
  if (isPlainObject(standingPortrait) && isPlainObject(standingPortrait.claims_by_standing)) {
    lines.push("What this room's claims were checked against");
    STANDING_IDS.forEach((id) => {
      const n = Number(standingPortrait.claims_by_standing[id]) || 0;
      lines.push('  ' + STANDING_WORDS[id].label + ': ' + n + ' - moves when ' + STANDING_WORDS[id].moves_when);
    });
    lines.push('  ' + HELD_WORDS.label + ': ' + (Number(standingPortrait.held) || 0) + ' - moves when ' + HELD_WORDS.moves_when);
  }
  lines.push('A count is not a verdict. Only a person confirms a claim.');
  return lines;
}

function renderClaimViewLines(claim) {
  const lines = [];
  lines.push('Claim: ' + claim.text);
  lines.push('Claim id: ' + claim.claim_id);
  lines.push('Confirmation status: ' + claim.confirmation.review_status + ' - ' + claim.confirmation.note);
  if (typeof claim.standing === 'string' && Object.prototype.hasOwnProperty.call(STANDING_WORDS, claim.standing)) {
    lines.push('Checked against: ' + STANDING_WORDS[claim.standing].label + '. It moves when ' + STANDING_WORDS[claim.standing].moves_when + '.');
  }
  lines.push('Checking record: ' + claim.checking_record.status + ' - ' + claim.checking_record.status_note);
  const records = claim.checking_record.records || [];
  if (records.length === 0) {
    lines.push('  (no checks recorded yet)');
  } else {
    records.forEach((r, i) => {
      lines.push('  ' + (i + 1) + '. checked against: ' + r.against_id + ' (' + r.against_kind + ')');
      lines.push('     ' + r.rung_display + ' | method: ' + r.method + ' | result: ' + r.result);
      let byLine = '     by: ' + r.checked_by;
      if (r.checked_by_id) byLine += ' (' + r.checked_by_id + ')';
      byLine += ' | when: ' + r.checked_at;
      lines.push(byLine);
      if (r.note_handle) lines.push('     note: ' + r.note_handle);
      if (r.resolves_dispute === true) lines.push('     a person marked the earlier contradiction answered');
    });
  }
  return lines;
}

function renderClaimListLines(claims) {
  if (!Array.isArray(claims) || claims.length === 0) {
    return ['  (no claims filed in this room yet)'];
  }
  return claims.map((c) => (
    '  - ' + c.claim_id + ' | checking: ' + c.checking_status +
    ' | confirmation: ' + c.review_status + ' | ' + c.text_preview +
    (typeof c.standing === 'string' && Object.prototype.hasOwnProperty.call(STANDING_WORDS, c.standing)
      ? ' | ' + STANDING_WORDS[c.standing].label : '')
  ));
}

