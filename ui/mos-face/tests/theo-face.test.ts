test('G1 asset: loadFaceAsset returns null for text that is not the asset', () => {
  const parsed = JSON.parse(ASSET_TEXT) as { states: { id: string; pose: Record<string, unknown> }[] }
  const copy = (): typeof parsed => JSON.parse(ASSET_TEXT) as typeof parsed
  const bad: [string, string][] = []

  bad.push(['not json', 'this is not json'])
  bad.push(['empty text', ''])
  bad.push(['an array', '[]'])
  bad.push(['no states', '{"version":"1.0"}'])

  const ten = copy()
  ten.states.pop()
  bad.push(['10 states', JSON.stringify(ten)])

  const noEye = copy()
  delete noEye.states[0]!.pose.e1
  bad.push(['a pose without e1', JSON.stringify(noEye)])

  const shortBar = copy()
  shortBar.states[2]!.pose.s = [1, 2, 3]
  bad.push(['a bar with 3 numbers', JSON.stringify(shortBar)])

  const nan = copy()
  nan.states[3]!.pose.r = [236, 'x']
  bad.push(['a crossing point with text', JSON.stringify(nan)])

  const odd = copy()
  odd.states[4]!.pose.plane = '#00FF00'
  bad.push(['a plane color that is not a token', JSON.stringify(odd)])

  const swapped = copy()
  swapped.states[0]!.id = 'zzz'
  bad.push(['an unknown state id', JSON.stringify(swapped)])

  const noSource = copy() as unknown as { states: Record<string, unknown>[] }
  noSource.states[1]!.source = ''
  bad.push(['an empty source', JSON.stringify(noSource)])

  for (const [name, text] of bad) expect(`${name} ${loadFaceAsset(text) === null}`).toBe(`${name} true`)
})

