// Phase 380 plan 12 (D-10, MOD380-09): the canon Theo faces, drawn from the copied asset.
//
// Source of the geometry: the mos-brand book e947a5d (read only), segment identity/theo, asset
// asset-fa8504998f.json (400 unit master), drawn by the renderer asset-d96217b320.js. The asset is
// copied byte for byte into ui/mos-face/assets (tests/test-380-theo-faces.cjs checks the hash).
// No pose number is typed in this file: the numbers come from the asset text in the fixture, and
// the expected drawing comes from the attributes that the canon renderer itself set (the fixture
// is generated by scripts/theo-faces.cjs with a fake DOM).
//
// G1 asset loading   G2 composition equals the canon renderer   G3 raster properties
// G5 load paths      (G4, the 44 pins, is in theo-face-pin.test.ts)
// Only the asset text and canary-free data. Hyphens only.

const IDS = ['rest', 'listen', 'search', 'found', 'challenge', 'contradiction', 'reframe', 'limit', 'decision', 'boundary', 'handover']
const TOKENS = new Set(['#F7F5EE', '#111111', '#FFFFFF', '#1F3FBF', '#D6281F', '#F2C200', '#4B4943'])
const NAME = 'asset-fa8504998f.json'

const asset = (): FaceAsset => {
  const loaded = loadFaceAsset(ASSET_TEXT)
  if (loaded === null) throw new Error('the canon asset text did not load')

  return loaded
}

