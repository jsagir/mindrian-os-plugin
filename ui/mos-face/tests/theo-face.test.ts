// ---- G2 composition ---------------------------------------------------------------------------

const NUMERIC = new Set(['x', 'y', 'width', 'height', 'stroke-width'])

// A canon record in comparable form: numeric attributes as numbers, the rest as text.
const normal = (attrs: Record<string, string>): Record<string, string | number> =>
  Object.fromEntries(Object.entries(attrs).map(([key, value]) => [key, NUMERIC.has(key) ? Number(value) : value]))

// The same list as text with the keys of every record in sorted order (the order the renderer set them in does not matter).
const sorted = (list: Record<string, string | number>[]): string =>
  JSON.stringify(list.map(one => Object.fromEntries(Object.entries(one).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))))

// The records a Part stands for (the bar stands for two: the group and its rect).
function recordsOf(part: Part, wanted: Record<string, string | number>[]): Record<string, string | number>[] {
  const out: Record<string, string | number>[] = []
  const shape = (): Record<string, string | number> => {
    const one: Record<string, string | number> = { x: part.x, y: part.y, width: part.width, height: part.height, fill: part.fill }
    if (part.stroke !== undefined) one.stroke = part.stroke
    if (part.strokeWidth !== undefined) one['stroke-width'] = part.strokeWidth

    return one
  }
  if (part.rotate !== undefined) {
    out.push({ transform: `translate(${part.rotate.x} ${part.rotate.y}) rotate(${part.rotate.deg})` })
    out.push(shape())

    return out
  }
  const one = shape()
  // The ground sets no x and no y in the canon (both are 0 by default).
  const want = wanted[0] ?? {}
  if (want.x === undefined && one.x === 0) delete one.x
  if (want.y === undefined && one.y === 0) delete one.y
  out.push(one)

  return out
}

test('G2 composition: composeFace equals the attributes that the canon renderer set, for all 11 states', () => {
  const loaded = asset()
  expect(Object.keys(CANON)).toEqual(IDS)
  for (const id of IDS) {
    const canon: CanonRecord[] = CANON[id] ?? []
    const parts = composeFace(loaded, id)
    expect(parts).not.toBeNull()
    const list = parts ?? []
    // The part order is the canon order (the bar group and its rect come as one Part).
    expect(`${id} ${list.map(one => one.name).join(',')}`).toBe(`${id} ground,plane,vertical,horizontal,bar,one,two,frame`)
    const got: Record<string, string | number>[] = []
    let at = 0
    for (const part of list) {
      const wantedHere = canon.slice(at, at + (part.rotate !== undefined ? 2 : 1)).map(rec => normal(rec.attrs))
      got.push(...recordsOf(part, wantedHere))
      at += part.rotate !== undefined ? 2 : 1
    }
    const want = canon.map(rec => normal(rec.attrs))
    expect(`${id} ${sorted(got)}`).toBe(`${id} ${sorted(want)}`)
  }
})

test('G2 composition: the hollow face and the tilted face are composed as the canon says', () => {
  const loaded = asset()
  const hand = composeFace(loaded, 'handover') ?? []
  const bar = hand.find(one => one.name === 'bar')
  expect(bar?.fill).toBe('#FFFFFF')
  expect(bar?.strokeWidth).toBe(8)
  for (const name of ['one', 'two']) {
    const eye = hand.find(one => one.name === name)
    expect(eye?.fill).toBe('#FFFFFF')
    expect(eye?.strokeWidth).toBe(8)
  }
  const rest = composeFace(loaded, 'rest') ?? []
  expect(rest.find(one => one.name === 'bar')?.rotate?.deg).not.toBe(0)
  expect(rest.find(one => one.name === 'one')?.strokeWidth).toBe(0)
  expect(composeFace(loaded, 'nope')).toBeNull()
})

// ---- G3 raster --------------------------------------------------------------------------------

const SIZES = [6, 8, 12, 16]
const PLANE_STATES = ['search', 'found', 'challenge', 'contradiction', 'reframe', 'decision', 'boundary']

const count = (grid: string[][], color: string): number => grid.reduce((sum, row) => sum + row.filter(cell => cell === color).length, 0)

test('G3 raster: an n by n grid of the seven token colors, at 4 sizes, for all 11 states', () => {
  const loaded = asset()
  for (const id of IDS) {
    for (const n of SIZES) {
      const grid = rasterFace(loaded, id, n)
      expect(grid).not.toBeNull()
      const g = grid ?? []
      expect(`${id} ${n} rows ${g.length}`).toBe(`${id} ${n} rows ${n}`)
      for (const row of g) expect(`${id} ${n} cols ${row.length}`).toBe(`${id} ${n} cols ${n}`)
      const strange = g.flat().filter(cell => !TOKENS.has(cell))
      expect(`${id} ${n} ${strange.join(',')}`).toBe(`${id} ${n} `)
    }
  }
  expect(rasterFace(loaded, 'nope', 12)).toBeNull()
})

test('G3 raster: no tick and no loop; the same call gives the same grid', () => {
  const loaded = asset()
  expect(rasterFace.length).toBe(3)
  for (const id of IDS) {
    expect(JSON.stringify(rasterFace(loaded, id, 12))).toBe(JSON.stringify(rasterFace(loaded, id, 12)))
  }
})

test('G3 raster: the plane color covers at least 8 percent of the grid at size 12', () => {
  const loaded = asset()
  for (const id of PLANE_STATES) {
    const plane = loaded.states.find(one => one.id === id)?.pose.plane ?? ''
    const grid = rasterFace(loaded, id, 12) ?? []
    const share = count(grid, plane) / 144
    expect(`${id} ${plane} ${share >= 0.08}`).toBe(`${id} ${plane} true`)
  }
})

test('G3 raster: the 11 faces are pairwise different at size 12, and at every other size too', () => {
  const loaded = asset()
  for (const n of SIZES) {
    const seen = new Map<string, string>()
    for (const id of IDS) {
      const key = JSON.stringify(rasterFace(loaded, id, n))
      const other = seen.get(key)
      expect(`${n}: ${id} equals ${other ?? 'nothing'}`).toBe(`${n}: ${id} equals nothing`)
      seen.set(key, id)
    }
  }
})

test('G3 raster: each eye shows its own color at the pixel that holds its center (a hollow face shows ink outline instead)', () => {
  const loaded = asset()
  for (const one of loaded.states) {
    for (const n of [8, 12, 16]) {
      const grid = rasterFace(loaded, one.id, n) ?? []
      const px = 400 / n
      for (const [eye, color] of [
        [one.pose.e1, one.pose.c1],
        [one.pose.e2, one.pose.c2],
      ] as const) {
        const cell = grid[Math.floor(eye[1] / px)]?.[Math.floor(eye[0] / px)]
        if (one.pose.hollow) {
          // The outline of a hollow shape is ink or white inside; at these sizes the outline can fill the shape.
          expect(`${one.id} ${n} hollow ${cell === '#111111' || cell === '#FFFFFF'}`).toBe(`${one.id} ${n} hollow true`)
        } else {
          expect(`${one.id} ${n} ${cell}`).toBe(`${one.id} ${n} ${color}`)
        }
      }
    }
  }
})

test('G3 raster: the divider and the ground line show as ink at every size (a thin bar is widened to one pixel)', () => {
  const loaded = asset()
  for (const one of loaded.states) {
    for (const n of SIZES) {
      const grid = rasterFace(loaded, one.id, n) ?? []
      const px = 400 / n
      const col = Math.floor(one.pose.r[0] / px)
      const row = Math.floor(one.pose.r[1] / px)
      expect(`${one.id} ${n} cross ${grid[row]?.[col]}`).toBe(`${one.id} ${n} cross #111111`)
    }
  }
})

